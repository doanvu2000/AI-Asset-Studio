"""Recipe catalog as Markdown for agents: the MCP resource `asset-studio://recipes` (live, from the core) and the
skill reference `integrations/.../references/recipes.md` (generated offline from the recipe YAML files)."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from studio_core.paths import recipes_dir

HEADER = "# AI Asset Studio — recipe catalog"
GENERATED_NOTE = "<!-- generated by scripts/gen_agent_docs.py from core/studio_core/recipes/*.yaml; do not edit -->"
_KIND_USES = {"comfy": "ComfyUI GPU", "views": "ComfyUI GPU", "retex": "ComfyUI GPU", "mesh": "ComfyUI GPU",
              "blender": "Blender", "claude": "Claude", "codex": "Codex", "storyboard": "Claude", "tts": "TTS"}
_LANE_USES = {"gpu": "ComfyUI GPU", "blender": "Blender", "cloud": "Claude"}


def _uses(steps: list[dict[str, Any]]) -> list[str]:
    out: list[str] = []
    for s in steps:
        kind = str(s.get("kind", ""))
        use = _LANE_USES.get(str(s.get("lane"))) or _KIND_USES.get(kind.split(".", 1)[0])
        if use and use not in out:
            out.append(use)
    return out


def _input_line(name: str, spec: dict[str, Any]) -> str:
    t = spec.get("type", "text")
    bits = [t]
    if spec.get("ext"):
        bits.append("." + "/.".join(spec["ext"]))
    if "default" in spec and spec["default"] not in ("", None):
        bits.append(f"default {spec['default']!r}")
    elif "default" not in spec and spec.get("required", True):
        bits.append("required")
    if spec.get("options"):
        bits.append("one of " + ", ".join(str(o) for o in spec["options"]))
    if spec.get("min") is not None or spec.get("max") is not None:
        bits.append(f"{spec.get('min', '')}..{spec.get('max', '')}")
    if spec.get("path") == "dir":
        bits.append("absolute folder path")
    label = str(spec.get("label") or "").strip()
    return f"  - `{name}` ({'; '.join(bits)})" + (f" — {label}" if label else "")


def recipe_markdown(r: dict[str, Any]) -> str:
    steps = r.get("steps") or []
    gates = [s["id"] for s in steps if str(s.get("kind", "")).startswith("gate.")]
    uses = _uses(steps)
    desc = " ".join(str(r.get("description") or "").split())
    lines = [f"## `{r['id']}` — {r.get('name', r['id'])}", "", desc, ""]
    lines.append(f"- runs on: {', '.join(uses) if uses else 'CPU only'}"
                 + (f"; gates: {', '.join(gates)}" if gates else "; no gates"))
    outs = r.get("outputs") or {}
    if outs:
        lines.append(f"- outputs: {', '.join(f'`{o}`' for o in outs)}")
    inputs = r.get("inputs") or {}
    if inputs:
        lines.append("- inputs:")
        lines.extend(_input_line(n, s if isinstance(s, dict) else {}) for n, s in inputs.items())
    return "\n".join(lines).rstrip() + "\n"


def catalog_markdown(recipes: list[dict[str, Any]], *, generated: bool = False) -> str:
    rs = sorted(recipes, key=lambda r: r["id"])
    gpu = [r["id"] for r in rs if any(u in ("ComfyUI GPU", "Blender") for u in _uses(r.get("steps") or []))]
    head = [HEADER, ""]
    if generated:
        head += [GENERATED_NOTE, ""]
    head += [f"{len(rs)} recipes. File inputs (image/mesh/file/video) take absolute local paths or blob hashes. "
             f"Recipes on ComfyUI GPU / Blender ({len(gpu)}) take minutes and use the GPU one at a time; the rest "
             "run on CPU or Claude in seconds.", "",
             "Index: " + ", ".join(f"`{r['id']}`" for r in rs), ""]
    return "\n".join(head) + "\n" + "\n".join(recipe_markdown(r) for r in rs)


def load_yaml_recipes(folder: Path | None = None) -> list[dict[str, Any]]:
    out = []
    for p in sorted((folder or recipes_dir()).glob("*.yaml")):
        doc = yaml.safe_load(p.read_text(encoding="utf-8"))
        if isinstance(doc, dict) and doc.get("id"):
            out.append(doc)
    return out


def generated_catalog() -> str:
    return catalog_markdown(load_yaml_recipes(), generated=True)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Write the recipe catalog used by the agent skill.")
    p.add_argument("out", type=Path, nargs="+", help="recipes.md file(s) to (re)write")
    p.add_argument("--check", action="store_true", help="exit 1 if a file is out of date instead of writing")
    args = p.parse_args(argv)
    text = generated_catalog()
    stale = 0
    for out in args.out:
        current = out.read_text(encoding="utf-8") if out.is_file() else None
        if current == text:
            continue
        if args.check:
            print(f"out of date: {out}", file=sys.stderr)
            stale += 1
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {out}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
