"""Skybox export (op.pano_cubemap): Unity Skybox/Panoramic + Skybox/6 Sided materials with an editor script that puts
one on RenderSettings and aims the sun; Godot Sky (PanoramaSkyMaterial), Environment and a WorldEnvironment scene."""
from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

from studio_core.export.source import Files, Source

MATERIAL_FILE_ID = 2100000
BUILTIN = "0000000000000000f000000000000000"
# Built-in shader ids in unity_builtin_extra (checked in Editor 6000.3: shader.name of the imported .mat).
PANORAMIC_SHADER_ID = 108
SIX_SIDED_SHADER_ID = 104
# Skybox/Panoramic shows the panorama centre at -Z with no rotation (rendered in Editor 6000.3); 90° brings it to
# Unity's forward (+Z) so it matches the 6 Sided material and the sun direction.
UNITY_PANO_ROTATION = 90
# 6 Sided property per face of ours (x right, y up, z forward = Unity +Z); the labels in Unity's shader name the
# opposite sides ("Left [+X]") because they describe the cube from outside.
UNITY_FACE_PROPS = (("_FrontTex", "front"), ("_BackTex", "back"), ("_LeftTex", "right"), ("_RightTex", "left"),
                    ("_UpTex", "up"), ("_DownTex", "down"))
FACE_ROLES = ("front", "right", "back", "left", "up", "down")


def skybox_set(step: Any, blobs: Any) -> tuple[dict[str, Any] | None, dict[str, Path]]:
    """skybox.json and its files, also when a gate passed it through under another port name."""
    from studio_core.ops.pano import SKYBOX_FILE, SKYBOX_TYPE

    for refs in step.outputs.values():
        for ref in refs:
            if (ref.name or "") != SKYBOX_FILE:
                continue
            try:
                doc = json.loads(blobs.path(ref.hash).read_bytes())
                if doc.get("type") != SKYBOX_TYPE:
                    return None, {}
                files = {"pano": blobs.path(str(doc["pano"]["hash"])),
                         "irradiance": blobs.path(str(doc["irradiance"]["hash"]))}
                files.update({f: blobs.path(str(doc["faces"][f]["hash"])) for f in FACE_ROLES})
                if not all(p.is_file() for p in files.values()):
                    return None, {}
                return doc, files
            except (OSError, ValueError, KeyError, TypeError):
                return None, {}
    return None, {}


def _light(src: Source) -> dict[str, Any]:
    return (src.skybox or {}).get("light") or {}


def _rgb(hex_color: str) -> tuple[float, float, float]:
    h = (hex_color or "#ffffff").lstrip("#")
    try:
        return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore[return-value]
    except ValueError:
        return 1.0, 1.0, 1.0


def _tex_env(prop: str, guid: str | None) -> str:
    tex = f"{{fileID: 2800000, guid: {guid}, type: 3}}" if guid else "{fileID: 0}"
    return f"    - {prop}:\n        m_Texture: {tex}\n        m_Scale: {{x: 1, y: 1}}\n        m_Offset: {{x: 0, y: 0}}\n"


def skybox_material(name: str, shader_id: int, textures: list[tuple[str, str]], floats: dict[str, float],
                    keywords: list[str]) -> str:
    kw = "".join(f"  - {k}\n" for k in keywords)
    return f"""%YAML 1.1
%TAG !u! tag:unity3d.com,2011:
--- !u!21 &{MATERIAL_FILE_ID}
Material:
  serializedVersion: 8
  m_ObjectHideFlags: 0
  m_CorrespondingSourceObject: {{fileID: 0}}
  m_PrefabInstance: {{fileID: 0}}
  m_PrefabAsset: {{fileID: 0}}
  m_Name: {name}
  m_Shader: {{fileID: {shader_id}, guid: {BUILTIN}, type: 0}}
  m_Parent: {{fileID: 0}}
  m_ModifiedSerializedProperties: 0
  m_ValidKeywords:{chr(10) + kw.rstrip(chr(10)) if kw else " []"}
  m_InvalidKeywords: []
  m_LightmapFlags: 4
  m_EnableInstancingVariants: 0
  m_DoubleSidedGI: 0
  m_CustomRenderQueue: -1
  stringTagMap: {{}}
  disabledShaderPasses: []
  m_LockedProperties:
  m_SavedProperties:
    serializedVersion: 3
    m_TexEnvs:
{"".join(_tex_env(p, g) for p, g in textures)}    m_Ints: []
    m_Floats:
{"".join(f"    - {k}: {v}{chr(10)}" for k, v in floats.items())}    m_Colors:
    - _Tint: {{r: 0.5, g: 0.5, b: 0.5, a: 0.5}}
  m_BuildTextureStacks: []
  m_AllowLocking: 1
"""


def _unity_texture_meta(src: Source, g: str, path: Path, *, pano: bool) -> str:
    from studio_core.export.pbr import _image_size
    from studio_core.export.unity import texture_meta

    meta = texture_meta(src.asset, g, None, _image_size(path), src.ppu, False, repeat=True)
    if pano:
        # Mip selection jumps across the u = 0/1 wrap and draws a thin line down the seam; a sky never minifies much.
        return meta.replace("enableMipMap: 1", "enableMipMap: 0", 1).replace("wrapV: 0", "wrapV: 1", 1)
    return meta.replace("wrapU: 0", "wrapU: 1", 1).replace("wrapV: 0", "wrapV: 1", 1).replace("wrapW: 0", "wrapW: 1", 1)


SKYBOX_SCRIPT = """// Generated by AI Asset Studio: puts an exported skybox material on the open scene (ambient + reflections from it)
// and aims the sun light at the brightest spot of the panorama, read from <asset>_skybox.json next to the material.
using System;
using System.IO;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;

public static class AssetStudioSkybox
{
    [Serializable] class SunInfo { public float[] dir; public string color; public float strength; public bool distinct; }
    [Serializable] class SkyInfo { public SunInfo light; }

    [MenuItem("Assets/Asset Studio/Use As Skybox", true)]
    static bool CanUse() => Selection.activeObject is Material m && m.shader != null && m.shader.name.StartsWith("Skybox/");

    [MenuItem("Assets/Asset Studio/Use As Skybox")]
    static void UseSelected() => Apply((Material)Selection.activeObject);

    public static void Apply(Material mat)
    {
        RenderSettings.skybox = mat;
        RenderSettings.ambientMode = AmbientMode.Skybox;
        RenderSettings.defaultReflectionMode = DefaultReflectionMode.Skybox;
        var info = ReadInfo(mat);
        if (info != null && info.light != null && info.light.distinct && info.light.dir != null && info.light.dir.Length == 3)
            AimSun(info.light);
        DynamicGI.UpdateEnvironment();
        EditorSceneManager.MarkSceneDirty(EditorSceneManager.GetActiveScene());
        Debug.Log("Asset Studio: skybox " + mat.name + " applied");
    }

    // Batch use: -executeMethod AssetStudio.AssetStudioSkybox.ApplyFromArgs -skyboxMaterial Assets/.../x_panoramic.mat
    public static void ApplyFromArgs()
    {
        var args = Environment.GetCommandLineArgs();
        var i = Array.IndexOf(args, "-skyboxMaterial");
        var mat = i >= 0 && i + 1 < args.Length ? AssetDatabase.LoadAssetAtPath<Material>(args[i + 1]) : null;
        if (mat == null) throw new ArgumentException("pass -skyboxMaterial <Assets/... .mat>");
        Apply(mat);
    }

    static SkyInfo ReadInfo(Material mat)
    {
        var path = AssetDatabase.GetAssetPath(mat);
        if (string.IsNullOrEmpty(path)) return null;
        var stem = mat.name;
        var cut = stem.LastIndexOf('_');
        if (cut > 0) stem = stem.Substring(0, cut);
        var json = Path.Combine(Path.GetDirectoryName(path), stem + "_skybox.json");
        return File.Exists(json) ? JsonUtility.FromJson<SkyInfo>(File.ReadAllText(json)) : null;
    }

    static void AimSun(SunInfo s)
    {
        var sun = RenderSettings.sun;
        if (sun == null)
            foreach (var l in UnityEngine.Object.FindObjectsByType<Light>(FindObjectsSortMode.None))
                if (l.type == LightType.Directional) { sun = l; break; }
        if (sun == null)
        {
            sun = new GameObject("Sun").AddComponent<Light>();
            sun.type = LightType.Directional;
            sun.shadows = LightShadows.Soft;
        }
        var toSun = new Vector3(s.dir[0], s.dir[1], s.dir[2]);
        sun.transform.rotation = Quaternion.LookRotation(-toSun.normalized, Vector3.up);
        if (ColorUtility.TryParseHtmlString(s.color, out var c)) sun.color = c;
        sun.intensity = Mathf.Lerp(0.6f, 1.3f, s.strength);
        RenderSettings.sun = sun;
    }
}
"""


def unity_files(src: Source) -> tuple[Files, list[str]]:
    from studio_core.export.sheet import cs_namespace
    from studio_core.export.unity import guid, native_meta

    a, u, fl = src.asset, src.uid, src.skybox_files
    files: Files = []
    guids: dict[str, str] = {}
    for role in ("pano", *FACE_ROLES, "irradiance"):
        rel = f"Skybox/{a}_{role}.png"
        guids[role] = guid(u, a, rel)
        files += [(rel, fl[role]),
                  (f"{rel}.meta", _unity_texture_meta(src, guids[role], fl[role], pano=role == "pano").encode())]
    pano_rel, six_rel = f"Skybox/{a}_panoramic.mat", f"Skybox/{a}_6sided.mat"
    pano_mat = skybox_material(f"{a}_panoramic", PANORAMIC_SHADER_ID, [("_MainTex", guids["pano"])],
                               {"_Exposure": 1, "_ImageType": 0, "_Layout": 0, "_Mapping": 1, "_MirrorOnBack": 0,
                                "_Rotation": UNITY_PANO_ROTATION}, ["_MAPPING_LATITUDE_LONGITUDE_LAYOUT"])
    six_mat = skybox_material(f"{a}_6sided", SIX_SIDED_SHADER_ID, [(p, guids[f]) for p, f in UNITY_FACE_PROPS],
                              {"_Exposure": 1, "_Rotation": 0}, [])
    files += [(pano_rel, pano_mat.encode()), (f"{pano_rel}.meta", native_meta(guid(u, a, pano_rel),
                                                                               MATERIAL_FILE_ID).encode()),
              (six_rel, six_mat.encode()), (f"{six_rel}.meta", native_meta(guid(u, a, six_rel),
                                                                           MATERIAL_FILE_ID).encode()),
              (f"Skybox/{a}_skybox.json", json.dumps(src.skybox, indent=1, ensure_ascii=False).encode()),
              ("Editor/AssetStudioSkybox.cs", cs_namespace(SKYBOX_SCRIPT).encode())]
    sun = _light(src)
    sun_note = (f" và xoay Directional Light về hướng nắng (cao {sun.get('elevation')}°, lệch {sun.get('azimuth')}° "
                "so với hướng trước)") if sun.get("distinct") else ""
    face = (src.skybox or {}).get("face_size")
    notes = [f"- Skybox/{a}_panoramic.mat (Skybox/Panoramic, ảnh 2:1 tắt mipmap để không lộ "
             f"đường nối) và {a}_6sided.mat (Skybox/6 Sided, 6 mặt {face}px): chuột phải material > Asset Studio > "
             f"Use As Skybox để gắn vào RenderSettings, ánh sáng môi trường + phản chiếu lấy từ skybox{sun_note}. "
             "Dùng được cả Built-in RP lẫn URP. Window > Rendering > Lighting > Generate Lighting nếu cần bake.",
             f"- Skybox/{a}_irradiance.png: ánh sáng khuếch tán đã tích phân (tham khảo màu ambient); "
             f"{a}_skybox.json ghi hướng nắng, màu ambient, điểm mối nối."]
    return files, notes


def _basis_for(to_sun: tuple[float, float, float]) -> list[float]:
    """Godot Transform3D basis (row-major text order) whose -Z axis points from the sun to the scene."""
    z = to_sun
    up = (0.0, 1.0, 0.0) if abs(z[1]) < 0.99 else (1.0, 0.0, 0.0)
    x = (up[1] * z[2] - up[2] * z[1], up[2] * z[0] - up[0] * z[2], up[0] * z[1] - up[1] * z[0])
    n = math.sqrt(sum(c * c for c in x)) or 1.0
    x = (x[0] / n, x[1] / n, x[2] / n)
    y = (z[1] * x[2] - z[2] * x[1], z[2] * x[0] - z[0] * x[2], z[0] * x[1] - z[1] * x[0])
    return [x[0], y[0], z[0], x[1], y[1], z[1], x[2], y[2], z[2]]


def _g(v: float) -> str:
    return f"{v:.5g}"


def godot_files(src: Source) -> tuple[Files, list[str]]:
    a, fl = src.asset, src.skybox_files
    sun = _light(src)
    files: Files = [(f"Skybox/{a}_pano.png", fl["pano"]), (f"Skybox/{a}_irradiance.png", fl["irradiance"])]
    files += [(f"Skybox/Faces/{a}_{f}.png", fl[f]) for f in FACE_ROLES]
    sky = (f'[gd_resource type="Sky" load_steps=3 format=3]\n\n'
           f'[ext_resource type="Texture2D" path="{a}_pano.png" id="1_pano"]\n\n'
           f'[sub_resource type="PanoramaSkyMaterial" id="PanoramaSkyMaterial_1"]\n'
           f'panorama = ExtResource("1_pano")\n\n'
           f'[resource]\nsky_material = SubResource("PanoramaSkyMaterial_1")\nradiance_size = 3\n')
    env = (f'[gd_resource type="Environment" load_steps=2 format=3]\n\n'
           f'[ext_resource type="Sky" path="{a}_sky.tres" id="1_sky"]\n\n'
           f'[resource]\nbackground_mode = 2\nsky = ExtResource("1_sky")\nambient_light_source = 3\n'
           f'reflected_light_source = 2\ntonemap_mode = 2\nsky_rotation = Vector3(0, 3.14159, 0)\n')
    d = sun.get("dir") or [0.0, 1.0, 0.0]
    # PanoramaSkyMaterial puts the panorama centre at +Z (rendered in Godot 4.7); sky_rotation 180° turns it to
    # Godot's forward (-Z), so the light only flips z.
    basis = _basis_for((float(d[0]), float(d[1]), -float(d[2])))
    r, g, b = _rgb(str(sun.get("color") or "#ffffff"))
    energy = 0.6 + 0.7 * float(sun.get("strength") or 0.5)
    tf = ", ".join(_g(v) for v in basis)
    scene = (f'[gd_scene load_steps=2 format=3]\n\n'
             f'[ext_resource type="Environment" path="{a}_environment.tres" id="1_env"]\n\n'
             f'[node name="{a}_world" type="Node3D"]\n\n'
             f'[node name="WorldEnvironment" type="WorldEnvironment" parent="."]\nenvironment = ExtResource("1_env")\n\n'
             f'[node name="Sun" type="DirectionalLight3D" parent="."]\n'
             f'transform = Transform3D({tf}, 0, 10, 0)\n'
             f'light_color = Color({_g(r)}, {_g(g)}, {_g(b)}, 1)\nlight_energy = {_g(energy)}\n'
             f'shadow_enabled = true\nvisible = {"true" if sun.get("distinct") else "false"}\n\n'
             f'[node name="Camera3D" type="Camera3D" parent="."]\n'
             f'transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 1.6, 0)\nfov = 70.0\n')
    files += [(f"Skybox/{a}_sky.tres", sky.encode()), (f"Skybox/{a}_environment.tres", env.encode()),
              (f"Skybox/{a}_world.tscn", scene.encode()),
              (f"Skybox/{a}_skybox.json", json.dumps(src.skybox, indent=1, ensure_ascii=False).encode())]
    notes = [f"- Skybox/{a}_sky.tres (Sky + PanoramaSkyMaterial) và {a}_environment.tres (nền = sky, ambient + "
             f"phản chiếu lấy từ sky): kéo environment vào WorldEnvironment của scene, hoặc mở {a}_world.tscn mẫu "
             "(WorldEnvironment + Sun DirectionalLight3D đã xoay theo hướng nắng + Camera3D). Faces/ là 6 mặt cube nếu "
             "cần cubemap riêng."]
    return files, notes
