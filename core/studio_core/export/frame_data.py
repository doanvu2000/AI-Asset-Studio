"""Combat frame data export (op.frame_data): frame_data.json for both engines, a Unity FrameData ScriptableObject with
AnimationEvents patched into the sheet's clips, and a Godot scene whose AnimationPlayer toggles Hurtbox/Hitbox
Area2D shapes per frame and calls emit_frame_event on the root."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from studio_core.contracts import BlobStore, StepRow
from studio_core.export.sheet import SHARED_SCRIPT_NOTE, cs_namespace, ident
from studio_core.export.source import Files, Source

ASSET_ID = 11400000
# Fixed so frame data from several characters in one project shares one script identity.
DATA_GUID = "6d3f8a1c7b2e4950a1c4e8f27b9d3056"
RECEIVER_GUID = "9b4e2a7d5c1f4863b0d9a3e6f81c2475"
EVENT_FUNCTION = "OnFrameEvent"
GODOT_SCRIPT_FILE = "asset_studio_frame_events.gd"


def frame_data_set(step: StepRow, blobs: BlobStore) -> tuple[dict[str, Any] | None, Path | None]:
    """op.frame_data's frame_data.json and its sheet, also when a gate passed them through under other port names."""
    from studio_core.ops.frame_data import FRAME_FILE, FRAME_TYPE

    doc, sheet = None, None
    for refs in step.outputs.values():
        for ref in refs:
            if (ref.name or "") == FRAME_FILE and doc is None:
                try:
                    cand = json.loads(blobs.path(ref.hash).read_bytes())
                except (OSError, ValueError):
                    return None, None
                if not isinstance(cand, dict) or cand.get("type") != FRAME_TYPE or not cand.get("tracks"):
                    return None, None
                doc = cand
    for ref in step.outputs.get("sheet") or []:
        if blobs.path(ref.hash).is_file():
            sheet = blobs.path(ref.hash)
            break
    return doc, sheet


def _f(v: float) -> str:
    return f"{v:.6g}"


def _num(v: float) -> str:
    s = _f(v)
    return s if any(ch in s for ch in ".e") else f"{s}.0"


def _unit(box: list[int], pivot: list[float], ppu: float) -> tuple[tuple[float, float], tuple[float, float]]:
    """Cell px (top-left origin, y down) -> engine units around the pivot, y up."""
    cx, cy = box[0] + box[2] / 2 - pivot[0], pivot[1] - (box[1] + box[3] / 2)
    return (round(cx / ppu, 5), round(cy / ppu, 5)), (round(box[2] / ppu, 5), round(box[3] / ppu, 5))


def json_bytes(src: Source) -> bytes:
    doc = {k: v for k, v in (getattr(src, "frame_data", None) or {}).items() if k != "sheet_meta"}
    return json.dumps(doc, indent=1).encode()


def json_file(src: Source) -> tuple[str, bytes]:
    return f"FrameData/{src.asset}_frame_data.json", json_bytes(src)


DATA_SCRIPT = cs_namespace("""using System;
using UnityEngine;

// Generated by AI Asset Studio: hurtboxes, hitbox and combat events for every animation frame of a sprite sheet.
[CreateAssetMenu(menuName = "Asset Studio/Frame Data", fileName = "FrameData")]
public class FrameData : ScriptableObject
{
    // Boxes are in world units around the sprite pivot, y up (the sprite's own local space).
    [Serializable] public class Box { public Vector2 center; public Vector2 size; }
    [Serializable] public class Frame { public Box[] hurtboxes; public bool hasHitbox; public Box hitbox; }
    [Serializable] public class FrameEvent { public int frame; public float time; public string name; }

    [Serializable]
    public class Track
    {
        public string name;
        public string clip;
        public string dir;
        public float fps;
        public bool loop;
        public int[] active;
        public Frame[] frames;
        public FrameEvent[] events;
    }

    public string assetName;
    public float ppu;
    public Track[] tracks;

    public Track GetTrack(string trackName)
    {
        foreach (var t in tracks)
            if (t.name == trackName) return t;
        return null;
    }

    public Frame GetFrame(string trackName, float time)
    {
        var t = GetTrack(trackName);
        if (t == null || t.frames.Length == 0) return null;
        int i = Mathf.FloorToInt(time * t.fps);
        i = t.loop ? ((i % t.frames.Length) + t.frames.Length) % t.frames.Length : Mathf.Clamp(i, 0, t.frames.Length - 1);
        return t.frames[i];
    }
}
""")

RECEIVER_SCRIPT = cs_namespace("""using System;
using UnityEngine;
using UnityEngine.Events;

// Generated by AI Asset Studio: put it on the Animator's GameObject; the clips' AnimationEvents call OnFrameEvent with
// attack_start, hit_active, recover or footstep.
public class FrameEventReceiver : MonoBehaviour
{
    [Serializable] public class NameEvent : UnityEvent<string> { }

    public event Action<string> FrameEvent;
    public NameEvent onFrameEvent = new NameEvent();

    public void OnFrameEvent(string eventName)
    {
        FrameEvent?.Invoke(eventName);
        onFrameEvent.Invoke(eventName);
    }
}
""")


def _q(s: Any) -> str:
    return json.dumps(str(s or ""))


def _vec(v: tuple[float, float]) -> str:
    return f"{{x: {_f(v[0])}, y: {_f(v[1])}}}"


def _box_yaml(box: list[int] | None, pivot: list[float], ppu: float, pad: str) -> str:
    c, s = _unit(box, pivot, ppu) if box else ((0.0, 0.0), (0.0, 0.0))
    return f"{pad}center: {_vec(c)}\n{pad}size: {_vec(s)}\n"


def unity_asset(src: Source, script_guid: str = DATA_GUID) -> str:
    from studio_core.export.unity import HEADER

    doc = src.frame_data or {}
    pivot, ppu = doc["pivot"], src.ppu or 100.0
    out = [HEADER, f"--- !u!114 &{ASSET_ID}\nMonoBehaviour:\n  m_ObjectHideFlags: 0\n",
           "  m_CorrespondingSourceObject: {fileID: 0}\n  m_PrefabInstance: {fileID: 0}\n  m_PrefabAsset: {fileID: 0}\n",
           "  m_GameObject: {fileID: 0}\n  m_Enabled: 1\n  m_EditorHideFlags: 0\n",
           f"  m_Script: {{fileID: 11500000, guid: {script_guid}, type: 3}}\n  m_Name: {src.asset}_frame_data\n",
           f"  m_EditorClassIdentifier: \n  assetName: {_q(src.asset)}\n  ppu: {_f(ppu)}\n  tracks:\n"]
    for t in doc["tracks"]:
        out.append(f"  - name: {t['name']}\n    clip: {t['clip']}\n    dir: {t['dir'] or _q('')}\n"
                   f"    fps: {_f(t['fps'])}\n    loop: {int(bool(t['loop']))}\n")
        out.append("    active:\n" + "".join(f"    - {a}\n" for a in t["active"]) if t["active"] else "    active: []\n")
        out.append("    frames:\n")
        for fr in t["frames"]:
            if fr["hurtboxes"]:
                out.append("    - hurtboxes:\n")
                for b in fr["hurtboxes"]:
                    c, s = _unit(b, pivot, ppu)
                    out.append(f"      - center: {_vec(c)}\n        size: {_vec(s)}\n")
            else:
                out.append("    - hurtboxes: []\n")
            hit = fr["hitbox"]
            out.append(f"      hasHitbox: {1 if hit else 0}\n      hitbox:\n"
                       + _box_yaml(hit["box"] if hit else None, pivot, ppu, "        "))
        out.append("    events:\n" if t["events"] else "    events: []\n")
        for e in t["events"]:
            out.append(f"    - frame: {e['frame']}\n      time: {_f(e['time'])}\n      name: {e['name']}\n")
    return "".join(out)


def events_yaml(events: list[dict[str, Any]]) -> str:
    rows = "".join(f"  - time: {_f(e['time'])}\n    functionName: {EVENT_FUNCTION}\n    data: {e['name']}\n"
                   "    objectReferenceParameter: {fileID: 0}\n    floatParameter: 0\n    intParameter: 0\n"
                   "    messageOptions: 0\n" for e in events)
    return f"  m_Events:\n{rows}"


def patch_clips(files: Files, src: Source) -> Files:
    """Returns `files` with the AnimationEvents written into each `Animations/<track>.anim` the sheet export made."""
    doc = src.frame_data or {}
    by_path = {f"Animations/{t['name']}.anim": t["events"] for t in doc.get("tracks") or [] if t["events"]}
    out: Files = []
    for rel, data in files:
        if rel in by_path and isinstance(data, bytes):
            text = data.decode("utf-8")
            if "  m_Events: []\n" in text:
                data = text.replace("  m_Events: []\n", events_yaml(by_path[rel]), 1).encode("utf-8")
        out.append((rel, data))
    return out


def script_meta(g: str) -> str:
    from studio_core.export.npc import script_meta as meta

    return meta(g)


def unity_files(src: Source) -> tuple[Files, list[str]]:
    from studio_core.export.unity import guid, native_meta

    asset_rel = f"FrameData/{src.asset}_frame_data.asset"
    json_rel, json_data = json_file(src)
    files: Files = [(json_rel, json_data),
                    ("Scripts/FrameData.cs", DATA_SCRIPT.encode()),
                    ("Scripts/FrameData.cs.meta", script_meta(DATA_GUID).encode()),
                    ("Scripts/FrameEventReceiver.cs", RECEIVER_SCRIPT.encode()),
                    ("Scripts/FrameEventReceiver.cs.meta", script_meta(RECEIVER_GUID).encode()),
                    (asset_rel, unity_asset(src).encode()),
                    (f"{asset_rel}.meta", native_meta(guid(src.uid, src.asset, asset_rel), ASSET_ID).encode())]
    doc = src.frame_data or {}
    n_ev = sum(len(t["events"]) for t in doc.get("tracks") or [])
    note = (f"- {asset_rel}: ScriptableObject AssetStudio.FrameData (Scripts/FrameData.cs; code dùng `using AssetStudio;`) "
            f"— hurtbox / hitbox từng frame của {len(doc.get('tracks') or [])} clip (đơn vị world quanh pivot, y lên), "
            f"GetFrame(\"slash_S\", animator time). {n_ev} AnimationEvent đã ghi sẵn vào Animations/*.anim, gọi "
            f"{EVENT_FUNCTION}(attack_start | hit_active | recover | footstep) — gắn Scripts/FrameEventReceiver.cs lên "
            f"GameObject có Animator. {json_rel} chứa cùng dữ liệu (px ô) cho code tự đọc. Nhập nhiều nhân vật vào một "
            "project thì giữ một bản mỗi script (cùng GUID)" + SHARED_SCRIPT_NOTE + ".")
    return files, [note]


GODOT_SCRIPT = """extends Node2D
## Root of the combat scene from AI Asset Studio: the AnimationPlayer toggles Hurtbox/Hitbox shapes per frame and its
## method tracks call emit_frame_event (attack_start, hit_active, recover, footstep).

signal frame_event(event_name: StringName, animation: StringName)

@onready var player: AnimationPlayer = $AnimationPlayer
@onready var hurtbox: Area2D = $Hurtbox
@onready var hitbox: Area2D = $Hitbox


func play(animation: StringName) -> void:
	player.play(animation)


func emit_frame_event(event_name: String) -> void:
	frame_event.emit(StringName(event_name), player.current_animation)
"""


def _keys(times: list[float], values: list[str]) -> str:
    t = ", ".join(_f(x) for x in times)
    tr = ", ".join("1" for _ in times)
    return (f'tracks/{{i}}/keys = {{\n"times": PackedFloat32Array({t}),\n"transitions": PackedFloat32Array({tr}),\n'
            f'"update": 1,\n"values": [{", ".join(values)}]\n}}')


def _value_track(i: int, path: str, times: list[float], values: list[str]) -> str:
    head = (f'tracks/{i}/type = "value"\ntracks/{i}/imported = false\ntracks/{i}/enabled = true\n'
            f'tracks/{i}/path = NodePath("{path}")\ntracks/{i}/interp = 1\ntracks/{i}/loop_wrap = true\n')
    return head + _keys(times, values).replace("{i}", str(i))


def _method_track(i: int, times: list[float], names: list[str]) -> str:
    t = ", ".join(_f(x) for x in times)
    tr = ", ".join("1" for _ in times)
    vals = ", ".join(f'{{\n"args": ["{n}"],\n"method": &"emit_frame_event"\n}}' for n in names)
    return (f'tracks/{i}/type = "method"\ntracks/{i}/imported = false\ntracks/{i}/enabled = true\n'
            f'tracks/{i}/path = NodePath(".")\ntracks/{i}/interp = 1\ntracks/{i}/loop_wrap = true\n'
            f'tracks/{i}/keys = {{\n"times": PackedFloat32Array({t}),\n"transitions": PackedFloat32Array({tr}),\n'
            f'"values": [{vals}]\n}}')


def _shape_tracks(start: int, node: str, per_frame: list[list[int] | None], fps: float,
                  pivot: list[float]) -> tuple[list[str], int]:
    """disabled / shape size / position tracks of one CollisionShape2D; boxes in cell px, position from the pivot."""
    times = [i / fps for i in range(len(per_frame))]
    dis_t, dis_v = [], []
    for t, box in zip(times, per_frame):
        v = "true" if box is None else "false"
        if not dis_v or dis_v[-1] != v:
            dis_t.append(t)
            dis_v.append(v)
    out = [_value_track(start, f"{node}:disabled", dis_t, dis_v)]
    on = [(t, b) for t, b in zip(times, per_frame) if b is not None]
    if on:
        out.append(_value_track(start + 1, f"{node}:shape:size", [t for t, _ in on],
                                [f"Vector2({_num(b[2])}, {_num(b[3])})" for _, b in on]))
        out.append(_value_track(start + 2, f"{node}:position", [t for t, _ in on],
                                [f"Vector2({_num(b[0] + b[2] / 2 - pivot[0])}, {_num(b[1] + b[3] / 2 - pivot[1])})"
                                 for _, b in on]))
    return out, start + len(out)


def godot_tscn(src: Source) -> str:
    doc = src.frame_data or {}
    pivot = doc["pivot"]
    n_hurt = max((len(f["hurtboxes"]) for t in doc["tracks"] for f in t["frames"]), default=0) or 1
    subs = [f'[sub_resource type="RectangleShape2D" id="Shape_hurt{k}"]\nresource_local_to_scene = true\n'
            "size = Vector2(1, 1)\n" for k in range(n_hurt)]
    subs.append('[sub_resource type="RectangleShape2D" id="Shape_hit"]\nresource_local_to_scene = true\n'
                "size = Vector2(1, 1)\n")
    names: list[str] = []
    for k, t in enumerate(doc["tracks"]):
        fps = max(float(t["fps"]), 1e-6)
        n = len(t["frames"])
        tracks: list[str] = []
        idx = 0
        for h in range(n_hurt):
            boxes = [f["hurtboxes"][h] if h < len(f["hurtboxes"]) else None for f in t["frames"]]
            part, idx = _shape_tracks(idx, f"Hurtbox/Shape{h}", boxes, fps, pivot)
            tracks += part
        part, idx = _shape_tracks(idx, "Hitbox/Shape", [f["hitbox"]["box"] if f["hitbox"] else None
                                                       for f in t["frames"]], fps, pivot)
        tracks += part
        if t["events"]:
            tracks.append(_method_track(idx, [e["time"] for e in t["events"]], [e["name"] for e in t["events"]]))
        subs.append(f'[sub_resource type="Animation" id="Animation_{k}"]\nresource_name = "{t["name"]}"\n'
                    f'length = {_num(n / fps)}\nloop_mode = {1 if t["loop"] else 0}\nstep = {_f(1 / fps)}\n'
                    + "\n".join(tracks) + "\n")
        names.append(f'&"{t["name"]}": SubResource("Animation_{k}")')
    subs.append('[sub_resource type="AnimationLibrary" id="AnimationLibrary_main"]\n_data = {\n'
                + ",\n".join(names) + "\n}\n")
    steps = 1 + len(subs) + 1
    root = ident(src.asset, "combat")
    nodes = [f'[node name="{root}" type="Node2D"]\nscript = ExtResource("1_script")\n',
             '[node name="Hurtbox" type="Area2D" parent="."]\n']
    for h in range(n_hurt):
        nodes.append(f'[node name="Shape{h}" type="CollisionShape2D" parent="Hurtbox"]\n'
                     f'shape = SubResource("Shape_hurt{h}")\ndisabled = true\n')
    nodes += ['[node name="Hitbox" type="Area2D" parent="."]\n',
              '[node name="Shape" type="CollisionShape2D" parent="Hitbox"]\nshape = SubResource("Shape_hit")\n'
              "disabled = true\n",
              '[node name="AnimationPlayer" type="AnimationPlayer" parent="."]\nlibraries = {\n'
              '&"": SubResource("AnimationLibrary_main")\n}\n']
    head = (f'[gd_scene load_steps={steps} format=3]\n\n'
            f'[ext_resource type="Script" path="{GODOT_SCRIPT_FILE}" id="1_script"]\n\n')
    return head + "\n".join(subs) + "\n" + "\n".join(nodes)


def godot_files(src: Source) -> tuple[Files, list[str]]:
    json_rel, json_data = json_file(src)
    scene = f"{src.asset}_combat.tscn"
    files: Files = [(json_rel, json_data), (GODOT_SCRIPT_FILE, GODOT_SCRIPT.encode()),
                    (scene, godot_tscn(src).encode("utf-8"))]
    doc = src.frame_data or {}
    n_ev = sum(len(t["events"]) for t in doc.get("tracks") or [])
    note = (f"- {scene}: Node2D (script {GODOT_SCRIPT_FILE}) với Hurtbox / Hitbox (Area2D + CollisionShape2D) và một "
            f"AnimationPlayer {len(doc.get('tracks') or [])} animation trùng tên clip SpriteFrames (vd slash_S): track "
            f"bật/tắt `disabled`, đổi shape size + position theo từng frame (gốc = pivot chân, khớp offset AnimatedSprite2D "
            f"của {src.asset}.tscn), và {n_ev} method track gọi emit_frame_event(attack_start | hit_active | recover | "
            f"footstep) → signal frame_event. Dùng: đặt {src.asset}.tscn làm con của {scene}, `$AnimationPlayer.play"
            f"(\"slash_S\")` cùng lúc với sprite; hitbox.area_entered kết nối như thường. {json_rel} chứa cùng dữ liệu "
            "(px ô). Nhập nhiều nhân vật thì giữ một asset_studio_frame_events.gd (không class_name nên không trùng).")
    return files, [note]
