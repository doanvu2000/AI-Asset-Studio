"""Parallax background export (op.parallax_layers): layer sprites under Parallax/, a Unity prefab of Tiled
SpriteRenderers driven by AssetStudioParallax.cs, and a Godot 4 scene of Parallax2D nodes (repeat_size on X)."""
from __future__ import annotations

import json
from pathlib import Path

from studio_core.contracts import BlobStore, StepRow
from studio_core.export.sheet import cs_namespace, ident
from studio_core.export.source import Files, Source

# Fixed, so a second exported background in the same Unity project shares one script identity: deleting the
# duplicate .cs keeps every prefab's m_Script reference valid.
SCRIPT_GUID = "5f0c3a9e2d7b4e81a6c4b2f19d8e7a30"
SCRIPT_FILE = "AssetStudioParallax.cs"
UNITY_SCRIPT = cs_namespace("""// Generated by AI Asset Studio: endless horizontal parallax for one layer (SpriteRenderer in Tiled mode, 3 widths).
using UnityEngine;

public class AssetStudioParallax : MonoBehaviour
{
    [Tooltip("0 = fixed to the camera, 1 = moves with the world, > 1 = foreground")]
    public float scroll = 0.5f;
    public Transform target;
    float startX, width;

    void Start()
    {
        if (target == null && Camera.main != null) target = Camera.main.transform;
        var sr = GetComponent<SpriteRenderer>();
        width = sr != null && sr.sprite != null ? sr.sprite.bounds.size.x * Mathf.Abs(transform.lossyScale.x) : 0f;
        startX = transform.position.x - (target != null ? target.position.x * (1f - scroll) : 0f);
    }

    void LateUpdate()
    {
        if (target == null || width <= 0f) return;
        float camX = target.position.x;
        float x = startX + camX * (1f - scroll);
        x += Mathf.Round((camX - x) / width) * width;
        var p = transform.position;
        transform.position = new Vector3(x, p.y, p.z);
    }
}
""")
SCRIPT_META = f"""fileFormatVersion: 2
guid: {SCRIPT_GUID}
MonoImporter:
  externalObjects: {{}}
  serializedVersion: 2
  defaultReferences: []
  executionOrder: 0
  icon: {{instanceID: 0}}
  userData:
  assetBundleName:
  assetBundleVariant:
"""


def parallax_set(step: StepRow, blobs: BlobStore) -> tuple[list[tuple[str, Path, float]], tuple[int, int]]:
    """op.parallax_layers's parallax.json, also when a gate passed it through under another port name."""
    from studio_core.ops.parallax import PARALLAX_FILE, PARALLAX_TYPE

    for refs in step.outputs.values():
        for ref in refs:
            if (ref.name or "") != PARALLAX_FILE:
                continue
            try:
                doc = json.loads(blobs.path(ref.hash).read_bytes())
                if doc.get("type") != PARALLAX_TYPE:
                    return [], (0, 0)
                out, seen = [], set()
                for la in doc["layers"]:
                    name, path = ident(str(la["name"]), "layer"), blobs.path(str(la["hash"]))
                    if name in seen or not path.is_file():
                        continue
                    seen.add(name)
                    out.append((name, path, float(la.get("scroll", 1.0))))
                w, h = (int(v) for v in doc["size"])
                return out, (w, h)
            except (OSError, ValueError, KeyError, TypeError):
                return [], (0, 0)
    return [], (0, 0)


def _files(src: Source) -> list[tuple[str, str, Path, float]]:
    return [(n, f"{src.asset}_{i}_{n}.png", p, s) for i, (n, p, s) in enumerate(src.parallax)]


def _orders(src: Source) -> list[int]:
    """Background layers behind gameplay (negative), a faster-than-world layer in front of it."""
    n = len(src.parallax)
    return [100 if s > 1 else (i - n) * 10 for i, (_, _, s) in enumerate(src.parallax)]


def index_json(src: Source) -> bytes:
    w, h = src.parallax_size
    doc = {"asset": src.asset, "size": [w, h], "ppu": src.ppu, "axis": "x",
           "layers": [{"name": n, "file": f, "scroll": s, "order": o}
                      for (n, f, _, s), o in zip(_files(src), _orders(src))]}
    return json.dumps(doc, indent=1).encode()


def _behaviour(mb: int, go: int, scroll: float) -> str:
    return f"""--- !u!114 &{mb}
MonoBehaviour:
  m_ObjectHideFlags: 0
  m_CorrespondingSourceObject: {{fileID: 0}}
  m_PrefabInstance: {{fileID: 0}}
  m_PrefabAsset: {{fileID: 0}}
  m_GameObject: {{fileID: {go}}}
  m_Enabled: 1
  m_EditorHideFlags: 0
  m_Script: {{fileID: 11500000, guid: {SCRIPT_GUID}, type: 3}}
  m_Name:
  m_EditorClassIdentifier:
  scroll: {scroll:.6g}
  target: {{fileID: 0}}
"""


def unity_prefab(src: Source, guids: dict[str, str]) -> str:
    """Every layer sits with its bottom edge on y = 0, drawn Tiled 3 sprite widths wide so the script can re-centre
    it under the camera by whole widths."""
    from studio_core.export.damage import _go, _renderer, _transform
    from studio_core.export.unity import HEADER, file_id

    a, ppu = src.asset, src.ppu or 100.0
    w, h = src.parallax_size
    root, rtr = file_id("parallax", a, "go"), file_id("parallax", a, "transform")
    layers = _files(src)
    ids = [tuple(file_id("parallax", a, n, k) for k in ("go", "tr", "sr", "mb")) for n, *_ in layers]
    docs = [_go(root, [rtr], f"{a}_parallax"), _transform(rtr, root, (0, 0), [i[1] for i in ids], 0)]
    for (name, f, _, scroll), (go, tr, sr, mb), order in zip(layers, ids, _orders(src)):
        rend = _renderer(sr, go, guids[f], (3 * w / ppu, h / ppu), order).replace("m_DrawMode: 0", "m_DrawMode: 2")
        docs += [_go(go, [tr, sr, mb], name), _transform(tr, go, (0, h / 2 / ppu), [], rtr), rend,
                 _behaviour(mb, go, scroll)]
    return HEADER + "".join(docs)


def unity_layer_meta(asset: str, tex_guid: str, size: tuple[int, int], ppu: float, pixel: bool) -> str:
    """Single sprite, Full Rect mesh (Tiled draw mode needs it), wrap Repeat on U and Clamp on V."""
    from studio_core.export.unity import texture_meta

    meta = texture_meta(asset, tex_guid, None, size, ppu, pixel)
    return meta.replace("wrapU: 1", "wrapU: 0").replace("spriteMeshType: 1", "spriteMeshType: 0")


def unity_files(src: Source) -> tuple[Files, list[str]]:
    from studio_core.export.unity import guid, prefab_meta

    files: Files = []
    guids: dict[str, str] = {}
    for _, f, p, _ in _files(src):
        rel = f"Parallax/{f}"
        guids[f] = guid(src.uid, src.asset, rel)
        files += [(rel, p), (f"{rel}.meta", unity_layer_meta(src.asset, guids[f], _image_size(p), src.ppu,
                                                             src.pixel is True).encode())]
    prefab_rel = f"Parallax/{src.asset}_parallax.prefab"
    files += [(f"Parallax/{src.asset}_parallax.json", index_json(src)),
              (f"Parallax/{SCRIPT_FILE}", UNITY_SCRIPT.encode()), (f"Parallax/{SCRIPT_FILE}.meta", SCRIPT_META.encode()),
              (prefab_rel, unity_prefab(src, guids).encode()),
              (f"{prefab_rel}.meta", prefab_meta(guid(src.uid, src.asset, prefab_rel)).encode())]
    scrolls = ", ".join(f"{n} {s:g}" for n, _, s in src.parallax)
    note = (f"- Parallax/: {len(src.parallax)} lớp {src.asset}_<thứ tự>_<lớp>.png (trời đục, các lớp sau nền trong), "
            "Wrap Mode U = Repeat, Mesh Type = Full Rect. Kéo "
            f"{src.asset}_parallax.prefab vào scene: mỗi lớp là SpriteRenderer Draw Mode = Tiled rộng 3 lần ảnh + "
            f"{SCRIPT_FILE} (scroll: 0 = đứng yên theo camera, 1 = chạy theo thế giới, > 1 = tiền cảnh, Sorting "
            f"Order 100). Tốc độ: {scrolls}. Đáy các lớp ở y = 0; camera mặc định Camera.main (đổi ở Target). Xuất "
            f"nhiều nền vào cùng project: giữ 1 file {SCRIPT_FILE}, xoá bản trùng (cùng guid nên prefab vẫn chạy).")
    return files, [note]


def _num(v: float) -> str:
    s = f"{float(v):.6g}"
    return s if any(ch in s for ch in ".e") else f"{s}.0"


def godot_scene(src: Source) -> str:
    w, h = src.parallax_size
    ext, nodes = [], [f'[node name="{src.asset}_parallax" type="Node2D"]']
    for i, ((name, f, _, scroll), order) in enumerate(zip(_files(src), _orders(src))):
        ext.append(f'[ext_resource type="Texture2D" path="Parallax/{f}" id="{i}_{name}"]')
        nodes += ['', f'[node name="{name}" type="Parallax2D" parent="."]',
                  f"z_index = {10 if order > 0 else order}", f"scroll_scale = Vector2({_num(scroll)}, 1)",
                  f"repeat_size = Vector2({_num(w)}, 0)", '',
                  f'[node name="Sprite" type="Sprite2D" parent="{name}"]', f'texture = ExtResource("{i}_{name}")',
                  "centered = false", f"position = Vector2(0, {_num(-h)})"]
        if src.pixel is True:
            nodes.append("texture_filter = 1")
    return "\n".join(['[gd_scene format=3]', '', *ext, '', *nodes]) + "\n"


def godot_files(src: Source) -> tuple[Files, list[str]]:
    files: Files = [(f"Parallax/{f}", p) for _, f, p, _ in _files(src)]
    files += [(f"Parallax/{src.asset}_parallax.json", index_json(src)),
              (f"{src.asset}_parallax.tscn", godot_scene(src).encode())]
    note = (f"- {src.asset}_parallax.tscn (Godot 4.3+): mỗi lớp là Parallax2D (repeat_size = rộng ảnh, chỉ lặp trục "
            "X; scroll_scale.x = tốc độ cuộn, 0 = đứng theo camera, 1 = theo thế giới, > 1 = tiền cảnh z_index 10) "
            "chứa Sprite2D đáy ở y = 0. Cần Camera2D trong scene; zoom nhỏ hơn 1 mà hở mép thì tăng repeat_times. "
            "Ảnh trong Parallax/.")
    return files, [note]


def _image_size(p: Path) -> tuple[int, int]:
    from PIL import Image

    with Image.open(p) as im:
        return im.size
