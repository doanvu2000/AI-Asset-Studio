"""Isometric 2:1 export (op.iso_tiles, op.iso_prop). Unity: pre-sliced sprites at PPU = tile width (one cell =
1 x 0.5 units), a Tile asset per variant / direction and an editor script that builds <asset>_IsoGrid.prefab (Grid
cell layout Isometric, cell size 1 x 0.5, painted sample) and switches transparency sorting to the Y axis. Godot:
TileSet with tile_shape Isometric + Diamond Down layout and a y-sorted TileMapLayer scene with the same sample."""
from __future__ import annotations

import json
import struct
from pathlib import Path
from typing import Any

from studio_core.export.sheet import cs_namespace
from studio_core.export.source import Files, Source

TILE_FILE_ID = 11400000
PROP_SPACING = 2


def iso_set(step: Any, blobs: Any) -> tuple[dict[str, Any] | None, dict[str, Path]]:
    """iso_tiles.json / iso_prop.json and their images, also when a gate passed them through under another port."""
    from studio_core.ops.iso import ISO_PROP_FILE, ISO_PROP_TYPE, ISO_TILES_FILE, ISO_TILES_TYPE

    for refs in step.outputs.values():
        for ref in refs:
            name = ref.name or ""
            if name not in (ISO_TILES_FILE, ISO_PROP_FILE):
                continue
            try:
                doc = json.loads(blobs.path(ref.hash).read_bytes())
                if doc.get("type") == ISO_TILES_TYPE:
                    files = {v["name"]: blobs.path(str(v["hash"])) for v in doc["variants"]}
                    files["atlas"] = blobs.path(str(doc["atlas"]["hash"]))
                elif doc.get("type") == ISO_PROP_TYPE:
                    files = {d["name"]: blobs.path(str(d["hash"])) for d in doc["dirs"]}
                    files["atlas"] = blobs.path(str(doc["strip"]["hash"]))
                else:
                    return None, {}
                if not all(p.is_file() for p in files.values()):
                    return None, {}
                return doc, files
            except (OSError, ValueError, KeyError, TypeError):
                return None, {}
    return None, {}


def _is_prop(src: Source) -> bool:
    from studio_core.ops.iso import ISO_PROP_TYPE

    return (src.iso or {}).get("type") == ISO_PROP_TYPE


def _cells(src: Source) -> list[tuple[str, int, int, int, int]]:
    """(sprite name, x, y, w, h) inside the atlas strip, left to right."""
    doc = src.iso or {}
    if _is_prop(src):
        w, h = doc["canvas"]
        return [(f"{src.asset}_{d['dir']}", i * w, 0, w, h) for i, d in enumerate(doc["dirs"])]
    w, h = doc["tile"]
    return [(f"{src.asset}_tile_{i:02d}", i * w, 0, w, h) for i in range(len(doc["variants"]))]


def _pivot(src: Source) -> tuple[float, float]:
    doc = src.iso or {}
    if _is_prop(src):
        return float(doc["anchor"][0]), float(doc["anchor"][1])
    w, h = doc["tile"]
    return w / 2, h / 2


def _atlas_rel(src: Source) -> str:
    return f"Iso/{src.asset}_iso_{'prop' if _is_prop(src) else 'tiles'}.png"


def _sample(src: Source) -> list[tuple[int, int, int]]:
    """(cell x, cell y, sprite index) painted into the sample map: 4x4 ground, or the 4 prop turns apart."""
    doc = src.iso or {}
    if _is_prop(src):
        step = int(doc.get("cells", 1)) + PROP_SPACING - 1
        return [(i * step, 0, i) for i in range(len(doc["dirs"]))]
    n = int((doc.get("qa") or {}).get("grid") or 4)
    picks = list(doc.get("sample") or [])
    count = len(doc["variants"])
    return [(i, j, int(picks[j * n + i]) % count if j * n + i < len(picks) else (i + j) % count)
            for j in range(n) for i in range(n)]


def index_json(src: Source) -> bytes:
    doc = dict(src.iso or {})
    names = [c[0] for c in _cells(src)]
    out = {"asset": src.asset, "kind": "prop" if _is_prop(src) else "tiles", "tile": doc["tile"],
           "atlas": Path(_atlas_rel(src)).name, "tiles": names,
           "sample": [v for x, y, k in _sample(src) for v in (x, y, k)]}
    if _is_prop(src):
        out.update(cells=doc["cells"], canvas=doc["canvas"], anchor=doc["anchor"], foot=doc["foot"],
                   dirs=[d["dir"] for d in doc["dirs"]])
    out["qa"] = doc.get("qa")
    return json.dumps(out, indent=1).encode()


UNITY_EDITOR = """// Generated by AI Asset Studio: builds <asset>_IsoGrid.prefab next to <asset>_iso.json once the Tile assets are
// imported (Grid cell layout Isometric, cell size 1 x 0.5, sample painted) and turns on Y-axis transparency sorting
// (Built-in pipeline; URP 2D sets it on the Renderer2D asset). Menu Asset Studio > Build Iso Grids reruns it.
using System.IO;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.Tilemaps;

public class AssetStudioIso : AssetPostprocessor
{
    const string JsonName = "__JSON__";

    [System.Serializable] class Doc
    {
        public string asset;
        public string kind;
        public string[] tiles;
        public int[] sample;
    }

    static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom)
    {
        foreach (var p in imported)
        {
            if (Path.GetFileName(p) != JsonName) continue;
            var path = p;
            EditorApplication.delayCall += () => Build(path);
        }
    }

    [MenuItem("Asset Studio/Build Iso Grids/__ASSET__")]
    public static void BuildAll()
    {
        foreach (var g in AssetDatabase.FindAssets(Path.GetFileNameWithoutExtension(JsonName) + " t:TextAsset"))
        {
            var p = AssetDatabase.GUIDToAssetPath(g);
            if (Path.GetFileName(p) == JsonName) Build(p);
        }
    }

    public static bool Build(string jsonPath)
    {
        var text = AssetDatabase.LoadAssetAtPath<TextAsset>(jsonPath);
        if (text == null) return false;
        var doc = JsonUtility.FromJson<Doc>(text.text);
        var dir = Path.GetDirectoryName(jsonPath).Replace('\\\\', '/');
        var tiles = new TileBase[doc.tiles.Length];
        for (int i = 0; i < tiles.Length; i++)
        {
            tiles[i] = AssetDatabase.LoadAssetAtPath<TileBase>(dir + "/" + doc.tiles[i] + ".asset");
            if (tiles[i] == null) return false;
        }
        var root = new GameObject(doc.asset + "_IsoGrid");
        var grid = root.AddComponent<Grid>();
        grid.cellLayout = GridLayout.CellLayout.Isometric;
        grid.cellSize = new Vector3(1f, 0.5f, 1f);
        var layer = new GameObject(doc.kind == "prop" ? "Props" : "Ground");
        layer.transform.SetParent(root.transform, false);
        var map = layer.AddComponent<Tilemap>();
        var renderer = layer.AddComponent<TilemapRenderer>();
        // Props overlap their neighbours, so each tile sorts on its own; flat ground can batch in chunks.
        renderer.mode = doc.kind == "prop" ? TilemapRenderer.Mode.Individual : TilemapRenderer.Mode.Chunk;
        if (doc.kind == "prop") renderer.sortingOrder = 1;
        for (int i = 0; i + 2 < doc.sample.Length; i += 3)
            map.SetTile(new Vector3Int(doc.sample[i], doc.sample[i + 1], 0), tiles[doc.sample[i + 2]]);
        PrefabUtility.SaveAsPrefabAsset(root, dir + "/" + doc.asset + "_IsoGrid.prefab");
        Object.DestroyImmediate(root);
        // A project-wide setting: only fill it in while the project still has Unity's default, never override a choice.
        if (GraphicsSettings.transparencySortMode == TransparencySortMode.Default)
        {
            GraphicsSettings.transparencySortMode = TransparencySortMode.CustomAxis;
            GraphicsSettings.transparencySortAxis = new Vector3(0f, 1f, 0f);
            AssetDatabase.SaveAssets();
            Debug.Log("Asset Studio: Graphics > Transparency Sort Mode = Custom Axis (0, 1, 0) for isometric sorting.");
        }
        else if (GraphicsSettings.transparencySortMode != TransparencySortMode.CustomAxis
                 || GraphicsSettings.transparencySortAxis != new Vector3(0f, 1f, 0f))
            Debug.LogWarning("Asset Studio: project Transparency Sort is " + GraphicsSettings.transparencySortMode + " "
                + GraphicsSettings.transparencySortAxis + "; isometric tiles need Custom Axis (0, 1, 0), left unchanged.");
        return true;
    }
}
"""


def unity_editor(src: Source) -> str:
    from studio_core.export.unity import guid

    body = UNITY_EDITOR.replace("__JSON__", f"{src.asset}_iso.json").replace("__ASSET__", src.asset)
    # One copy per export, each in its own namespace, so two iso exports in one project do not collide; a hash, not
    # the asset name, since a namespace named like a type it uses (AssetStudio.Grid) would hide UnityEngine.Grid.
    return cs_namespace(body, f"AssetStudio.Iso{guid(src.uid, src.asset, 'Iso/Editor/AssetStudioIso.cs')[:8]}")


def unity_files(src: Source) -> tuple[Files, list[str]]:
    from PIL import Image

    from studio_core.export.autotile import unity_tile
    from studio_core.export.npc import script_meta
    from studio_core.export.sheet import Cell, Layout
    from studio_core.export.unity import guid, native_meta, texture_meta

    doc = src.iso or {}
    atlas = _atlas_rel(src)
    with Image.open(src.iso_files["atlas"]) as im:
        size = im.size
    cells = _cells(src)
    lay = Layout(width=size[0], height=size[1], frame_w=cells[0][3], frame_h=cells[0][4], pivot=_pivot(src),
                 cells=[Cell(n, x, y, w, h) for n, x, y, w, h in cells])
    tile_w = int(doc["tile"][0])
    tex_guid = guid(src.uid, src.asset, atlas)
    # PPU = tile width: one iso cell is 1 x 0.5 units, the Grid cell size.
    files: Files = [(atlas, src.iso_files["atlas"]),
                    (f"{atlas}.meta", texture_meta(src.asset, tex_guid, lay, size, tile_w, src.is_pixel()).encode())]
    for name, *_ in cells:
        rel = f"Iso/{name}.asset"
        files += [(rel, unity_tile(src, tex_guid, name, name).encode()),
                  (f"{rel}.meta", native_meta(guid(src.uid, src.asset, rel), TILE_FILE_ID).encode())]
    json_rel = f"Iso/{src.asset}_iso.json"
    editor_rel = "Iso/Editor/AssetStudioIso.cs"
    files += [(json_rel, index_json(src)), (editor_rel, unity_editor(src).encode()),
              (f"{editor_rel}.meta", script_meta(guid(src.uid, src.asset, editor_rel)).encode())]
    what = (f"{len(cells)} hướng prop (SW/SE/NE/NW, pivot = tâm ô trước của chân đế {doc.get('cells', 1)}×"
            f"{doc.get('cells', 1)} ô)" if _is_prop(src) else f"{len(cells)} biến thể tile mặt đất")
    note = (f"- Iso/: {Path(atlas).name} ({what}, đã cắt sprite, PPU = {tile_w} nên 1 ô = 1×0.5 unit) + mỗi sprite một "
            f"Tile asset để tô bằng Tile Palette. Editor/AssetStudioIso.cs dựng Iso/{src.asset}_IsoGrid.prefab (Grid "
            "Cell Layout = Isometric, Cell Size 1×0.5, đã tô mẫu). Iso cần Transparency Sort Mode = Custom Axis (0,1,0): "
            "Built-in — script chỉ tự đặt khi project còn mặc định (Default), project đã chọn kiểu khác thì giữ nguyên và "
            "ghi cảnh báo vào Console, tự đổi ở Project Settings > Graphics; URP 2D: đặt Transparency Sort Axis trên "
            "Renderer2D. Prop: Tilemap Renderer Mode = Individual.")
    return files, [note]


def tile_map_data(cells: list[tuple[int, int, int, int]]) -> str:
    """TileMapLayer.tile_map_data (format 0): u16 version, then per cell i16 x, i16 y, u16 source, u16 atlas x,
    u16 atlas y, u16 alternative — checked against a scene Godot 4.7 saved itself."""
    data = struct.pack("<H", 0) + b"".join(struct.pack("<hhHHHH", x, y, s, ax, 0, 0) for x, y, s, ax in cells)
    return "PackedByteArray(" + ", ".join(str(b) for b in data) + ")"


def godot_tileset(src: Source) -> str:
    doc = src.iso or {}
    cells = _cells(src)
    w, h = doc["tile"]
    rw, rh = cells[0][3], cells[0][4]
    lines = ['[gd_resource type="TileSet" load_steps=3 format=3]', '',
             f'[ext_resource type="Texture2D" path="{_atlas_rel(src)}" id="1_atlas"]', '',
             '[sub_resource type="TileSetAtlasSource" id="TileSetAtlasSource_1"]', 'texture = ExtResource("1_atlas")',
             f"texture_region_size = Vector2i({rw}, {rh})"]
    ax, ay = _pivot(src)
    for i in range(len(cells)):
        lines.append(f"{i}:0/0 = 0")
        if _is_prop(src):
            # Godot draws a tile's region centred on the cell, shifted by -texture_origin: this puts the anchor there.
            lines.append(f"{i}:0/0/texture_origin = Vector2i({round(ax - rw / 2)}, {round(ay - rh / 2)})")
    lines += ['', '[resource]', "tile_shape = 1", "tile_layout = 5", f"tile_size = Vector2i({w}, {h})",
              'sources/0 = SubResource("TileSetAtlasSource_1")']
    return "\n".join(lines) + "\n"


def godot_scene(src: Source, tileset: str) -> str:
    layer = "Props" if _is_prop(src) else "Ground"
    data = tile_map_data([(x, y, 0, k) for x, y, k in _sample(src)])
    lines = ['[gd_scene load_steps=2 format=3]', '', f'[ext_resource type="TileSet" path="{tileset}" id="1_ts"]', '',
             f'[node name="{src.asset}_iso" type="Node2D"]', "y_sort_enabled = true", '',
             f'[node name="{layer}" type="TileMapLayer" parent="."]']
    if _is_prop(src):
        lines.append("y_sort_enabled = true")
    lines += [f"tile_map_data = {data}", 'tile_set = ExtResource("1_ts")']
    return "\n".join(lines) + "\n"


def godot_files(src: Source) -> tuple[Files, list[str]]:
    kind = "prop" if _is_prop(src) else "tiles"
    tres = f"{src.asset}_iso_{kind}_tileset.tres"
    files: Files = [(_atlas_rel(src), src.iso_files["atlas"]), (f"Iso/{src.asset}_iso.json", index_json(src)),
                    (tres, godot_tileset(src).encode()),
                    (f"{src.asset}_iso.tscn", godot_scene(src, tres).encode())]
    doc = src.iso or {}
    what = ("4 hướng prop là 4 ô của atlas, texture_origin đặt tâm ô trước của chân đế vào giữa cell"
            if _is_prop(src) else f"{len(doc['variants'])} biến thể tile")
    note = (f"- {tres}: TileSet tile_shape = Isometric, layout Diamond Down, ô {doc['tile'][0]}×{doc['tile'][1]} "
            f"({what}). {src.asset}_iso.tscn: Node2D y_sort + TileMapLayer đã tô mẫu; tô thêm bằng tab TileMap. "
            "Prop đặt trên một TileMapLayer riêng bật y_sort_enabled (cùng Node2D cha y-sort) để che nhau đúng.")
    return files, [note]
