"""Paper-doll export (op.paperdoll): equipment layer sheets sliced exactly like the character sheet plus sockets.json.
Unity gets a prefab whose child SpriteRenderers follow the body sprite by name (AssetStudioPaperdoll.cs); Godot a
scene with child AnimatedSprite2D layers and Marker2D sockets kept in sync by asset_studio_paperdoll.gd."""
