SCRIPT_FILE = "AssetStudioPaperdoll.cs"
TEXT_ASSET_ID = 4900000
UNITY_SCRIPT = cs_namespace("""// Generated by AI Asset Studio: equipment layers follow the body sprite frame by frame; sockets move per frame.
using System;
using System.Collections.Generic;
using UnityEngine;

public class AssetStudioPaperdoll : MonoBehaviour
{
    [Serializable] public class Layer { public string name; public SpriteRenderer renderer; public Sprite[] sprites; }
    [Serializable] class Socket { public string name; public float x, y, rot; public string z; }
    [Serializable] class Frame { public string cell; public Socket[] sockets; public string[] order; }
    [Serializable] class Doc { public Frame[] frames; }

    public SpriteRenderer body;
    public TextAsset sockets;
    public float ppu = 100f;
    [Tooltip("Sheet pivot in cell pixels, origin top-left")]
    public Vector2 pivot;
    public Transform socketRoot;
    public Layer[] layers = new Layer[0];

    readonly Dictionary<string, Frame> frames = new Dictionary<string, Frame>();
    readonly List<Dictionary<string, Sprite>> lookup = new List<Dictionary<string, Sprite>>();
    Sprite last;

    void Awake()
    {
        if (body == null) body = GetComponent<SpriteRenderer>();
        foreach (var l in layers)
        {
            var d = new Dictionary<string, Sprite>();
            if (l.sprites != null) foreach (var s in l.sprites) if (s != null) d[s.name] = s;
            lookup.Add(d);
        }
        if (sockets != null)
            foreach (var f in JsonUtility.FromJson<Doc>(sockets.text).frames) frames[f.cell] = f;
    }

    public bool TryGetSocket(string socket, out Transform t)
    {
        t = socketRoot != null ? socketRoot.Find(socket) : null;
        return t != null;
    }

    void LateUpdate()
    {
        var s = body != null ? body.sprite : null;
        if (s == last) return;
        last = s;
        Frame f = null;
        if (s != null) frames.TryGetValue(s.name, out f);
        for (int i = 0; i < layers.Length; i++)
        {
            var l = layers[i];
            if (l.renderer == null) continue;
            l.renderer.sprite = s != null && lookup[i].TryGetValue(s.name, out var hit) ? hit : null;
            int at = f != null && f.order != null ? Array.IndexOf(f.order, l.name) : i;
            l.renderer.sortingOrder = body.sortingOrder + 1 + Mathf.Max(at, 0);
        }
        if (f == null || f.sockets == null || socketRoot == null) return;
        foreach (var k in f.sockets)
        {
            var t = socketRoot.Find(k.name);
            if (t == null) continue;
            t.localPosition = new Vector3((k.x - pivot.x) / ppu, (pivot.y - k.y) / ppu, 0f);
            t.localRotation = Quaternion.Euler(0f, 0f, -k.rot);
        }
    }
}
""")
GODOT_SCRIPT_FILE = "asset_studio_paperdoll.gd"
GODOT_SCRIPT = """extends "asset_studio_sprite.gd"
## Equipment layers (child AnimatedSprite2D) follow this sprite's animation frame; Sockets/<name> Marker2D move per
## frame from the sockets JSON. Layers draw above the body, back-to-front by the frame's order.

@export var sockets: JSON
var _frames := {}
var _layers: Array[AnimatedSprite2D] = []
var _pivot := Vector2.ZERO


func _ready() -> void:
	for c in get_children():
		if c is AnimatedSprite2D:
			_layers.append(c)
	if sockets:
		var p: Array = sockets.data.get("pivot", [0, 0])
		_pivot = Vector2(p[0], p[1])
		for f in sockets.data.get("frames", []):
			_frames["%s:%d" % [f["anim"], int(f["frame"])]] = f
	frame_changed.connect(_sync)
	animation_changed.connect(_sync)
	_sync()


func socket(socket_name: String) -> Marker2D:
	return get_node_or_null("Sockets/" + socket_name) as Marker2D


func _sync() -> void:
	for layer in _layers:
		if layer.animation != animation and layer.sprite_frames.has_animation(animation):
			layer.animation = animation
		layer.frame = frame
	var f: Dictionary = _frames.get("%s:%d" % [animation, frame], {})
	if f.is_empty():
		return
	var order: Array = f.get("order", [])
	for layer in _layers:
		layer.z_index = 1 + maxi(order.find(String(layer.name)), 0)
	for s in f.get("sockets", []):
		var m := socket(String(s["name"]))
		if m:
			m.position = Vector2(s["x"], s["y"]) - _pivot
			m.rotation_degrees = s["rot"]
"""


def paperdoll_set(step: StepRow, blobs: BlobStore) -> tuple[dict[str, Any] | None, list[tuple[str, Path]],
                                                             tuple[Path, dict[str, Any]] | None]:
    """op.paperdoll's paperdoll.json (also when a gate passed it through): the doc with its sockets inlined, the
    layer sheets, and the character sheet + meta they were cut to match."""
    from studio_core.ops.paperdoll import DOLL_FILE, DOLL_TYPE

    for refs in step.outputs.values():
        for ref in refs:
            if (ref.name or "") != DOLL_FILE:
                continue
            try:
                doc = json.loads(blobs.path(ref.hash).read_bytes())
                if doc.get("type") != DOLL_TYPE:
                    return None, [], None
                doc["sockets_doc"] = json.loads(blobs.path(str(doc["sockets"])).read_bytes())
                meta = json.loads(blobs.path(str(doc["sheet_meta"])).read_bytes())
                sheet = blobs.path(str(doc["sheet"]))
                out, seen = [], set()
                for la in doc["layers"]:
                    name, path = ident(str(la["name"]), "layer"), blobs.path(str(la["hash"]))
                    if name in seen or not path.is_file():
                        continue
                    seen.add(name)
                    out.append((name, path))
                return doc, out, ((sheet, meta) if sheet.is_file() else None)
            except (OSError, ValueError, KeyError, TypeError):
                return None, [], None
    return None, [], None


def _layout(src: Source) -> Layout:
    return layout(src.meta or {}, src.clip_hint, directional_rows=True)


def _sockets_json(src: Source) -> bytes:
    return json.dumps((src.paperdoll or {}).get("sockets_doc") or {}, indent=1).encode()


def _layer_rel(src: Source, name: str) -> str:
    return f"{src.asset}_{name}_sheet.png"


def _unity_children(src: Source, lay: Layout, root_go: int, root_tr: int, guids: dict[str, str]) -> tuple[
        list[int], list[str], str]:
    from studio_core.export.damage import _go, _renderer, _transform
    from studio_core.export.unity import file_id

    a, ppu = src.asset, src.ppu or 100.0
    first = lay.tracks[0].cells[0] if lay.tracks else lay.cells[0]
    kids, docs, entries = [], [], ""
    for i, (name, _) in enumerate(src.paperdoll_layers):
        go, tr, sr = (file_id("paperdoll", a, name, k) for k in ("go", "tr", "sr"))
        layer_asset = f"{a}_{name}"
        rend = _renderer(sr, go, guids[name], (first.w / ppu, first.h / ppu), 1 + i)
        sprite = f"{{fileID: {file_id('sprite', layer_asset, first.name)}, guid: {guids[name]}, type: 3}}"
        rend = rend.replace(next(ln for ln in rend.splitlines() if ln.startswith("  m_Sprite:")), f"  m_Sprite: {sprite}")
        docs += [_go(go, [tr, sr], name), _transform(tr, go, (0, 0), [], root_tr), rend]
        kids.append(tr)
        refs = "".join(f"    - {{fileID: {file_id('sprite', layer_asset, c.name)}, guid: {guids[name]}, type: 3}}\n"
                       for c in lay.cells)
        entries += f"  - name: {name}\n    renderer: {{fileID: {sr}}}\n    sprites:\n{refs}"
    sgo, str_ = file_id("paperdoll", a, "sockets", "go"), file_id("paperdoll", a, "sockets", "tr")
    names = list(((src.paperdoll or {}).get("sockets_doc") or {}).get("sockets") or [])
    marks = [(n, file_id("paperdoll", a, "socket", n, "go"), file_id("paperdoll", a, "socket", n, "tr")) for n in names]
    docs += [_go(sgo, [str_], "Sockets"), _transform(str_, sgo, (0, 0), [t for _, _, t in marks], root_tr)]
    for n, go, tr in marks:
        docs += [_go(go, [tr], n), _transform(tr, go, (0, 0), [], str_)]
    kids.append(str_)
    return kids, docs, entries + f"  socketRoot: {{fileID: {str_}}}\n"


def unity_prefab(src: Source, lay: Layout, json_guid: str, guids: dict[str, str]) -> str:
    """The character prefab (same texture, controller and ids as <asset>.prefab) plus layer children, a Sockets
    child and the sync behaviour on the root."""
    from studio_core.export.unity import file_id, guid, prefab

    a, u = src.asset, src.uid
    tex_guid, ctrl_guid = guid(u, a, f"{a}.png"), (guid(u, a, f"{a}.controller") if lay.tracks else None)
    base = prefab(a, f"{a}_paperdoll", lay, tex_guid, src.ppu, ctrl_guid)
    go, tr, sr = file_id("go", a), file_id("transform", a), file_id("renderer", a)
    mb = file_id("paperdoll", a, "behaviour")
    kids, docs, fields = _unity_children(src, lay, go, tr, guids)
    base = base.replace("  m_Component:\n", f"  m_Component:\n  - component: {{fileID: {mb}}}\n", 1)
    base = base.replace("  m_Children: []\n", "  m_Children:\n" + "".join(f"  - {{fileID: {k}}}\n" for k in kids), 1)
    px, py = lay.pivot
    behaviour = f"""--- !u!114 &{mb}
MonoBehaviour:
  m_ObjectHideFlags: 0
  m_CorrespondingSourceObject: {{fileID: 0}}
  m_PrefabInstance: {{fileID: 0}}
  m_PrefabAsset: {{fileID: 0}}
  m_GameObject: {{fileID: {go}}}
  m_Enabled: 1
  m_EditorHideFlags: 0
  m_Script: {{fileID: 11500000, guid: {SCRIPT_GUID}, type: 3}}
  m_Name:
  m_EditorClassIdentifier:
  body: {{fileID: {sr}}}
  sockets: {{fileID: {TEXT_ASSET_ID}, guid: {json_guid}, type: 3}}
  ppu: {src.ppu:.6g}
  pivot: {{x: {px:.6g}, y: {py:.6g}}}
  layers:
{fields}"""
    return base + behaviour + "".join(docs)


def _script_meta(g: str) -> str:
    return (f"fileFormatVersion: 2\nguid: {g}\nMonoImporter:\n  externalObjects: {{}}\n  serializedVersion: 2\n"
            f"  defaultReferences: []\n  executionOrder: 0\n  icon: {{instanceID: 0}}\n  userData:\n"
            f"  assetBundleName:\n  assetBundleVariant:\n")


def _text_meta(g: str) -> str:
    return (f"fileFormatVersion: 2\nguid: {g}\nTextScriptImporter:\n  externalObjects: {{}}\n  userData:\n"
            f"  assetBundleName:\n  assetBundleVariant:\n")


def unity_files(src: Source) -> tuple[Files, list[str]]:
    from studio_core.export.unity import guid, prefab_meta, texture_meta

    if src.meta is None:
        return [], []
    a, u = src.asset, src.uid
    lay = _layout(src)
    files: Files = []
    guids: dict[str, str] = {}
    for name, path in src.paperdoll_layers:
        rel = _layer_rel(src, name)
        guids[name] = guid(u, a, rel)
        files += [(rel, path), (f"{rel}.meta", texture_meta(f"{a}_{name}", guids[name], lay, (lay.width, lay.height),
                                                            src.ppu, src.is_pixel()).encode())]
    json_rel, prefab_rel = f"{a}_sockets.json", f"{a}_paperdoll.prefab"
    json_guid = guid(u, a, json_rel)
    files += [(json_rel, _sockets_json(src)), (f"{json_rel}.meta", _text_meta(json_guid).encode()),
              (SCRIPT_FILE, UNITY_SCRIPT.encode()), (f"{SCRIPT_FILE}.meta", _script_meta(SCRIPT_GUID).encode())]
    if lay.cells:
        files += [(prefab_rel, unity_prefab(src, lay, json_guid, guids).encode()),
                  (f"{prefab_rel}.meta", prefab_meta(guid(u, a, prefab_rel)).encode())]
    names = ", ".join(n for n, _ in src.paperdoll_layers) or "không có"
    note = (f"- Paper-doll: {a}_<món>_sheet.png ({names}) cắt y hệt {a}.png (cùng tên sprite), {a}_sockets.json "
            f"(TextAsset). {a}_paperdoll.prefab = nhân vật + mỗi món một SpriteRenderer con + {SCRIPT_FILE}: mỗi "
            "LateUpdate lấy sprite cùng tên với sprite thân đang chạy (Animator chỉ cần điều khiển thân), xếp lớp "
            "theo order của khung, dời các Transform Sockets/<socket> (hand_r, hand_l, head, chest; rot đã đổi sang "
            "trục Unity). Tắt/bật GameObject con để thay đồ; gắn vật 2D riêng vào Sockets/hand_r. Xuất nhiều nhân vật "
            f"vào cùng project: giữ 1 file {SCRIPT_FILE}.")
    return files, [note]


def godot_scene(src: Source, lay: Layout) -> str:
    from studio_core.export.godot import _num, default_animation

    a = src.asset
    ox, oy = lay.frame_w / 2 - lay.pivot[0], lay.frame_h / 2 - lay.pivot[1]
    anim = default_animation(lay)
    ext = [f'[ext_resource type="PackedScene" path="{a}.tscn" id="1_body"]',
           f'[ext_resource type="Script" path="{GODOT_SCRIPT_FILE}" id="2_doll"]',
           f'[ext_resource type="JSON" path="{a}_sockets.json" id="3_sockets"]']
    nodes = [f'[node name="{a}_paperdoll" instance=ExtResource("1_body")]', 'script = ExtResource("2_doll")',
             'sockets = ExtResource("3_sockets")']
    for i, (name, _) in enumerate(src.paperdoll_layers):
        ext.append(f'[ext_resource type="SpriteFrames" path="{a}_{name}.tres" id="{4 + i}_{name}"]')
        nodes += ["", f'[node name="{name}" type="AnimatedSprite2D" parent="."]', f"z_index = {1 + i}"]
        if src.is_pixel():
            nodes.append("texture_filter = 1")
        nodes += [f'sprite_frames = ExtResource("{4 + i}_{name}")', f'animation = &"{anim}"',
                  f"offset = Vector2({_num(ox)}, {_num(oy)})"]
    nodes += ["", '[node name="Sockets" type="Node2D" parent="."]']
    for n in ((src.paperdoll or {}).get("sockets_doc") or {}).get("sockets") or []:
        nodes += ["", f'[node name="{n}" type="Marker2D" parent="Sockets"]']
    return "\n".join(["[gd_scene format=3]", "", *ext, "", *nodes]) + "\n"


def godot_files(src: Source) -> tuple[Files, list[str]]:
    from studio_core.export.godot import sprite_frames

    if src.meta is None:
        return [], []
    a = src.asset
    lay = _layout(src)
    files: Files = []
    for name, path in src.paperdoll_layers:
        rel = _layer_rel(src, name)
        files += [(rel, path), (f"{a}_{name}.tres", sprite_frames(lay, rel, None).encode())]
    files += [(f"{a}_sockets.json", _sockets_json(src)), (GODOT_SCRIPT_FILE, GODOT_SCRIPT.encode())]
    if lay.facing:
        files.append((f"{a}_paperdoll.tscn", godot_scene(src, lay).encode()))
    note = (f"- Paper-doll: {a}_<món>_sheet.png + {a}_<món>.tres (SpriteFrames cùng tên animation/khung với {a}.tres), "
            f"{a}_sockets.json. {a}_paperdoll.tscn = {a}.tscn + mỗi món một AnimatedSprite2D con + Sockets/<socket> "
            f"(Marker2D: hand_r, hand_l, head, chest); {GODOT_SCRIPT_FILE} (kế thừa asset_studio_sprite.gd, vẫn có "
            "face()) cho lớp con chạy theo animation/frame của thân, xếp z theo order, dời Marker2D mỗi khung. Ẩn "
            "node con để thay đồ; add_child vào socket(\"hand_r\") để gắn vật 2D riêng.")
    return files, [note]
