"""NPC pack export (op.npc_pack): portraits under NPC/, an engine JSON, and a typed data asset: Unity NpcData
ScriptableObject (.asset referencing the sprites and AudioClips by GUID) / Godot NpcData Resource (.tres)."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from studio_core.contracts import BlobStore, StepRow
from studio_core.export.sheet import ident
from studio_core.export.source import Files, Source

SPRITE_ID = 21300000
AUDIO_ID = 8300000
ASSET_ID = 11400000
# One GUID for every copy of the script, so .asset files from different NPC exports keep resolving after the
# duplicate NpcData.cs copies are deleted.
SCRIPT_GUID = "5a17c0de4e9d4c1fa3b2c0ffee000001"


def npc_set(step: StepRow, blobs: BlobStore) -> tuple[dict[str, Any] | None, list[tuple[str, Path]]]:
    """op.npc_pack's npc.json, also when a gate passed it through under another port name."""
    from studio_core.ops.npc import NPC_FILE, NPC_TYPE

    for refs in step.outputs.values():
        for ref in refs:
            if (ref.name or "") != NPC_FILE:
                continue
            try:
                doc = json.loads(blobs.path(ref.hash).read_bytes())
                if doc.get("type") != NPC_TYPE:
                    return None, []
                out, seen = [], set()
                for p in doc.get("portraits") or []:
                    name, path = ident(str(p["expression"]), "expression"), blobs.path(str(p["hash"]))
                    if name not in seen and path.is_file():
                        seen.add(name)
                        out.append((name, path))
                return doc, out
            except (OSError, ValueError, KeyError, TypeError):
                return None, []
    return None, []


def _clip_names(src: Source) -> dict[str, str]:
    """npc line stem (<lang>_<id>_1) → exported Audio/ file name (OGG preferred by bundle._audio)."""
    return {Path(n).stem: n for n, _ in src.audio}


def flat_lines(src: Source) -> list[dict[str, Any]]:
    clips = _clip_names(src)
    out = []
    for ln in (src.npc or {}).get("lines") or []:
        for lang, text in (ln.get("text") or {}).items():
            a = (ln.get("audio") or {}).get(lang) or {}
            name = clips.get(str(a.get("stem")))
            out.append({"id": ln["id"], "lang": lang, "category": ln.get("category", ""),
                        "expression": ln.get("expression", "neutral"), "text": text,
                        "audio": f"Audio/{name}" if name else None, "seconds": a.get("seconds"),
                        "cues": (ln.get("subtitles") or {}).get(lang) or []})
    return out


def portrait_file(src: Source, expr: str) -> str:
    return f"NPC/{src.asset}_{expr}.png"


def doc_json(src: Source) -> bytes:
    npc = src.npc or {}
    doc = {"name": npc.get("name"), "persona": npc.get("persona", ""), "languages": npc.get("languages") or [],
           "voice": npc.get("voice") or {},
           "portraits": {e: portrait_file(src, e) for e, _ in src.npc_portraits}, "lines": flat_lines(src)}
    return json.dumps(doc, ensure_ascii=False, indent=1).encode("utf-8")


UNITY_SCRIPT = """using System;
using System.Collections.Generic;
using UnityEngine;

// Generated by AI Asset Studio: an NPC's portraits by expression and its voiced lines per language with subtitle cues.
[CreateAssetMenu(menuName = "Asset Studio/NPC Data", fileName = "NpcData")]
public class NpcData : ScriptableObject
{
    [Serializable] public class Portrait { public string expression; public Sprite sprite; }
    [Serializable] public class Cue { public float start; public float end; public string text; }

    [Serializable]
    public class Line
    {
        public string id;
        public string lang;
        public string category;
        public string expression;
        [TextArea] public string text;
        public AudioClip clip;
        public Cue[] cues;
    }

    public string npcName;
    [TextArea] public string persona;
    public string[] languages;
    public Portrait[] portraits;
    public Line[] lines;

    public Sprite GetPortrait(string expression)
    {
        Sprite fallback = null;
        foreach (var p in portraits)
        {
            if (p.expression == expression) return p.sprite;
            if (p.expression == "neutral" || fallback == null) fallback = p.sprite;
        }
        return fallback;
    }

    public List<Line> GetLines(string category, string lang)
    {
        var result = new List<Line>();
        foreach (var l in lines)
            if (l.category == category && l.lang == lang) result.Add(l);
        return result;
    }

    public Line RandomLine(string category, string lang)
    {
        var pool = GetLines(category, lang);
        return pool.Count == 0 ? null : pool[UnityEngine.Random.Range(0, pool.Count)];
    }

    public string CueAt(Line line, float time)
    {
        foreach (var c in line.cues)
            if (time >= c.start && time < c.end) return c.text;
        return "";
    }
}
"""


def _q(s: Any) -> str:
    # JSON's ASCII escapes are valid YAML double-quoted scalars, and Unity reads them back as UTF-16 text.
    return json.dumps(str(s or ""))


def _ref(file_id: int, g: str | None) -> str:
    return f"{{fileID: {file_id}, guid: {g}, type: 3}}" if g else "{fileID: 0}"


def unity_asset(src: Source, sprite_guids: dict[str, str], clip_guids: dict[str, str]) -> str:
    from studio_core.export.unity import HEADER

    npc = src.npc or {}
    out = [HEADER, f"--- !u!114 &{ASSET_ID}\nMonoBehaviour:\n  m_ObjectHideFlags: 0\n",
           "  m_CorrespondingSourceObject: {fileID: 0}\n  m_PrefabInstance: {fileID: 0}\n  m_PrefabAsset: {fileID: 0}\n",
           "  m_GameObject: {fileID: 0}\n  m_Enabled: 1\n  m_EditorHideFlags: 0\n",
           f"  m_Script: {_ref(11500000, SCRIPT_GUID)}\n  m_Name: {src.asset}_npc\n  m_EditorClassIdentifier: \n",
           f"  npcName: {_q(npc.get('name'))}\n  persona: {_q(npc.get('persona'))}\n"]
    langs = npc.get("languages") or []
    out.append("  languages:\n" + "".join(f"  - {lang}\n" for lang in langs) if langs else "  languages: []\n")
    out.append("  portraits:\n" if src.npc_portraits else "  portraits: []\n")
    for e, _ in src.npc_portraits:
        out.append(f"  - expression: {e}\n    sprite: {_ref(SPRITE_ID, sprite_guids.get(e))}\n")
    lines = flat_lines(src)
    out.append("  lines:\n" if lines else "  lines: []\n")
    for ln in lines:
        clip = clip_guids.get(ln["audio"] or "")
        out.append(f"  - id: {ln['id']}\n    lang: {ln['lang']}\n    category: {ln['category']}\n"
                   f"    expression: {ln['expression']}\n    text: {_q(ln['text'])}\n    clip: {_ref(AUDIO_ID, clip)}\n")
        out.append("    cues:\n" if ln["cues"] else "    cues: []\n")
        for c in ln["cues"]:
            out.append(f"    - start: {c['start']}\n      end: {c['end']}\n      text: {_q(c['text'])}\n")
    return "".join(out)


def audio_meta(g: str) -> str:
    return (f"fileFormatVersion: 2\nguid: {g}\nAudioImporter:\n  externalObjects: {{}}\n  serializedVersion: 8\n"
            "  defaultSettings:\n    serializedVersion: 2\n    loadType: 0\n    sampleRateSetting: 0\n"
            "    sampleRateOverride: 44100\n    compressionFormat: 1\n    quality: 1\n    conversionMode: 0\n"
            "    preloadAudioData: 0\n  platformSettingOverrides: {}\n  forceToMono: 1\n  normalize: 0\n"
            "  loadInBackground: 0\n  ambisonic: 0\n  3D: 0\n  userData: \n  assetBundleName: \n"
            "  assetBundleVariant: \n")


def script_meta(g: str) -> str:
    return (f"fileFormatVersion: 2\nguid: {g}\nMonoImporter:\n  externalObjects: {{}}\n  serializedVersion: 2\n"
            "  defaultReferences: []\n  executionOrder: 0\n  icon: {instanceID: 0}\n  userData: \n"
            "  assetBundleName: \n  assetBundleVariant: \n")


def _image_size(p: Path) -> tuple[int, int]:
    from PIL import Image

    with Image.open(p) as im:
        return im.size


def unity_files(src: Source) -> tuple[Files, list[str]]:
    from studio_core.export.unity import guid, native_meta, texture_meta

    files: Files = []
    sprite_guids: dict[str, str] = {}
    for e, p in src.npc_portraits:
        rel = portrait_file(src, e)
        sprite_guids[e] = guid(src.uid, src.asset, rel)
        files += [(rel, p), (f"{rel}.meta", texture_meta(src.asset, sprite_guids[e], None, _image_size(p), src.ppu,
                                                         False).encode())]
    clip_guids: dict[str, str] = {}
    for ln in flat_lines(src):
        rel = ln["audio"]
        if rel and rel not in clip_guids:
            clip_guids[rel] = guid(src.uid, src.asset, rel)
            files.append((f"{rel}.meta", audio_meta(clip_guids[rel]).encode()))
    asset_rel = f"NPC/{src.asset}_npc.asset"
    files += [(f"NPC/{src.asset}_npc.json", doc_json(src)),
              ("Scripts/NpcData.cs", UNITY_SCRIPT.encode()), ("Scripts/NpcData.cs.meta", script_meta(SCRIPT_GUID).encode()),
              (asset_rel, unity_asset(src, sprite_guids, clip_guids).encode()),
              (f"{asset_rel}.meta", native_meta(guid(src.uid, src.asset, asset_rel), ASSET_ID).encode())]
    note = (f"- NPC/{src.asset}_npc.asset: ScriptableObject NpcData (Scripts/NpcData.cs) — {len(src.npc_portraits)} "
            f"chân dung theo biểu cảm, {len(flat_lines(src))} câu thoại (mỗi ngôn ngữ một dòng) gắn AudioClip trong "
            "Audio/ + cues phụ đề (giây). Dùng: GetPortrait(line.expression), RandomLine(\"idle\", \"vi\"), "
            f"CueAt(line, audioSource.time). NPC/{src.asset}_npc.json chứa cùng dữ liệu cho code tự đọc. Nhập nhiều "
            "NPC vào một project thì giữ một bản Scripts/NpcData.cs (cùng GUID).")
    return files, [note]


GODOT_SCRIPT_FILE = "npc_data.gd"
GODOT_SCRIPT = """class_name NpcData
extends Resource
## NPC pack from AI Asset Studio: portraits by expression, voiced lines per language with subtitle cues.

@export var npc_name := ""
@export_multiline var persona := ""
@export var languages: PackedStringArray = []
@export var portraits: Dictionary = {}
## Each line: id, lang, category, expression, text, audio (AudioStream or null), cues [{start, end, text}].
@export var lines: Array = []


func portrait(expression: String) -> Texture2D:
	return portraits.get(expression, portraits.get("neutral"))


func lines_for(category: String, lang: String) -> Array:
	return lines.filter(func(l): return l["category"] == category and l["lang"] == lang)


func random_line(category: String, lang: String) -> Dictionary:
	var pool := lines_for(category, lang)
	return {} if pool.is_empty() else pool.pick_random()


func cue_at(line: Dictionary, time: float) -> String:
	for c in line.get("cues", []):
		if time >= c["start"] and time < c["end"]:
			return c["text"]
	return ""
"""


def _gs(s: Any) -> str:
    return '"' + str(s or "").replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _gnum(v: Any) -> str:
    s = f"{float(v or 0):.6g}"
    return s if any(ch in s for ch in ".e") else f"{s}.0"


def godot_tres(src: Source) -> str:
    npc = src.npc or {}
    ext = [f'[ext_resource type="Script" path="{GODOT_SCRIPT_FILE}" id="1_script"]']
    ids: dict[str, str] = {}
    for i, (e, _) in enumerate(src.npc_portraits):
        ids[portrait_file(src, e)] = f"p{i}"
        ext.append(f'[ext_resource type="Texture2D" path="{portrait_file(src, e)}" id="p{i}"]')
    lines = flat_lines(src)
    for ln in lines:
        if ln["audio"] and ln["audio"] not in ids:
            ids[ln["audio"]] = f"a{len(ids)}"
            ext.append(f'[ext_resource type="AudioStream" path="{ln["audio"]}" id="{ids[ln["audio"]]}"]')
    portraits = ", ".join(f'"{e}": ExtResource("{ids[portrait_file(src, e)]}")' for e, _ in src.npc_portraits)
    rows = []
    for ln in lines:
        cues = ", ".join(f'{{"start": {_gnum(c["start"])}, "end": {_gnum(c["end"])}, "text": {_gs(c["text"])}}}'
                         for c in ln["cues"])
        audio = f'ExtResource("{ids[ln["audio"]]}")' if ln["audio"] else "null"
        rows.append(f'{{"id": {_gs(ln["id"])}, "lang": {_gs(ln["lang"])}, "category": {_gs(ln["category"])}, '
                    f'"expression": {_gs(ln["expression"])}, "text": {_gs(ln["text"])}, "audio": {audio}, '
                    f'"cues": [{cues}]}}')
    langs = ", ".join(_gs(lang) for lang in npc.get("languages") or [])
    return "\n".join([f'[gd_resource type="Resource" script_class="NpcData" load_steps={len(ext) + 1} format=3]', "",
                      *ext, "", "[resource]", 'script = ExtResource("1_script")',
                      f"npc_name = {_gs(npc.get('name'))}", f"persona = {_gs(npc.get('persona'))}",
                      f"languages = PackedStringArray({langs})", f"portraits = {{{portraits}}}",
                      "lines = [" + ", ".join(rows) + "]", ""])


def godot_files(src: Source) -> tuple[Files, list[str]]:
    files: Files = [(portrait_file(src, e), p) for e, p in src.npc_portraits]
    files += [(f"NPC/{src.asset}_npc.json", doc_json(src)), (GODOT_SCRIPT_FILE, GODOT_SCRIPT.encode()),
              (f"{src.asset}_npc.tres", godot_tres(src).encode("utf-8"))]
    note = (f"- {src.asset}_npc.tres: Resource NpcData ({GODOT_SCRIPT_FILE}) — {len(src.npc_portraits)} chân dung "
            f"(portraits[biểu cảm] → Texture2D), {len(flat_lines(src))} câu thoại (mỗi ngôn ngữ một Dictionary: id, "
            "lang, category, expression, text, audio = AudioStream trong Audio/, cues phụ đề theo giây). Dùng: "
            "var npc: NpcData = load(\"res://.../" + f"{src.asset}_npc.tres\"); var l = npc.random_line(\"idle\", "
            "\"vi\"); $Portrait.texture = npc.portrait(l.expression); $Voice.stream = l.audio; "
            "$Label.text = npc.cue_at(l, $Voice.get_playback_position()).")
    return files, [note]
