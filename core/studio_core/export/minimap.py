def unity_prefab(src: Source, map_guid: str, mask_guid: str) -> str:
    from studio_core.export.unity import HEADER, file_id

    a, size = src.asset, _display(src)
    ids = {k: file_id("minimap", a, k) for k in ("go", "rt", "cr", "img", "mask", "mgo", "mrt", "mcr", "raw")}
    image = _GRAPHIC.format(raycast=1) + f"""  m_Sprite: {{fileID: {SPRITE_SINGLE_ID}, guid: {mask_guid}, type: 3}}
  m_Type: 0
  m_PreserveAspect: 0
  m_FillCenter: 1
  m_FillMethod: 4
  m_FillAmount: 1
  m_FillClockwise: 1
  m_FillOrigin: 0
  m_UseSpriteMesh: 0
  m_PixelsPerUnitMultiplier: 1
"""
    raw = _GRAPHIC.format(raycast=0) + f"""  m_Texture: {{fileID: {TEXTURE_ID}, guid: {map_guid}, type: 3}}
  m_UVRect:
    serializedVersion: 2
    x: 0
    y: 0
    width: 1
    height: 1
"""
    docs = [
        _go(ids["go"], [ids["rt"], ids["cr"], ids["img"], ids["mask"]], f"{a}_minimap"),
        _rect(ids["rt"], ids["go"], [ids["mrt"]], 0, False, size),
        _canvas_renderer(ids["cr"], ids["go"]),
        _mono(ids["img"], ids["go"], UGUI_IMAGE, image),
        _mono(ids["mask"], ids["go"], UGUI_MASK, "  m_ShowMaskGraphic: 0\n"),
        _go(ids["mgo"], [ids["mrt"], ids["mcr"], ids["raw"]], "Map"),
        _rect(ids["mrt"], ids["mgo"], [], ids["rt"], True, size),
        _canvas_renderer(ids["mcr"], ids["mgo"]),
        _mono(ids["raw"], ids["mgo"], UGUI_RAW_IMAGE, raw),
    ]
    return HEADER + "".join(docs)


def unity_files(src: Source) -> tuple[Files, list[str]]:
    from PIL import Image

    from studio_core.export.unity import guid, prefab_meta, texture_meta

    n = _names(src)
    files: Files = []
    guids: dict[str, str] = {}
    for key in ("map", "mask", "framed"):
        rel = f"Minimap/{n[key]}"
        guids[key] = guid(src.uid, src.asset, rel)
        with Image.open(src.minimap_files[key]) as im:
            size = im.size
        files += [(rel, src.minimap_files[key]),
                  (f"{rel}.meta", texture_meta(f"{src.asset}_{key}", guids[key], None, size, 100.0, False).encode())]
    prefab_rel = f"Minimap/{src.asset}_minimap.prefab"
    files += [(f"Minimap/{n['json']}", index_json(src)),
              (prefab_rel, unity_prefab(src, guids["map"], guids["mask"]).encode()),
              (f"{prefab_rel}.meta", prefab_meta(guid(src.uid, src.asset, prefab_rel)).encode())]
    doc = src.minimap or {}
    shape = "tròn" if doc.get("shape") == "circle" else "vuông"
    note = (f"- Minimap/: {n['map']} (bản đồ + {len(doc.get('pois') or [])} POI), {n['mask']} (mask {shape}), "
            f"{n['framed']} (có viền, dùng làm ảnh tĩnh), {n['json']} (POI: x/y 0–1 tính từ góc trên-trái, px "
            f"pixel). Kéo {src.asset}_minimap.prefab vào một Canvas: Image + Mask (sprite mask) ôm RawImage \"Map\"; "
            "cuộn bản đồ theo người chơi bằng RawImage.uvRect.")
    return files, [note]


def _num(v: float) -> str:
    s = f"{float(v):.6g}"
    return s if any(ch in s for ch in ".e") else f"{s}.0"


def godot_scene(src: Source) -> str:
    n = _names(src)
    a, size = src.asset, _display(src)
    circle = (src.minimap or {}).get("shape") == "circle"
    ext = [f'[ext_resource type="Texture2D" path="Minimap/{n["map"]}" id="1_map"]']
    sub: list[str] = []
    mat: list[str] = []
    if circle:
        ext.append('[ext_resource type="Shader" path="Minimap/minimap_circle.gdshader" id="2_mask"]')
        sub = ['[sub_resource type="ShaderMaterial" id="ShaderMaterial_mask"]', 'shader = ExtResource("2_mask")',
               "shader_parameter/radius = 0.5", "shader_parameter/rim = 0.02", ""]
        mat = ['material = SubResource("ShaderMaterial_mask")']
    nodes = [f'[node name="{a}_minimap" type="TextureRect"]', *mat,
             f"custom_minimum_size = Vector2({_num(size)}, {_num(size)})",
             f"offset_right = {_num(size)}", f"offset_bottom = {_num(size)}",
             'texture = ExtResource("1_map")', "expand_mode = 1", "stretch_mode = 5"]
    return "\n".join(["[gd_scene format=3]", "", *ext, "", *sub, *nodes]) + "\n"


def godot_files(src: Source) -> tuple[Files, list[str]]:
    n = _names(src)
    files: Files = [(f"Minimap/{n[k]}", src.minimap_files[k]) for k in ("map", "mask", "framed")]
    files += [(f"Minimap/{n['json']}", index_json(src)),
              ("Minimap/minimap_circle.gdshader", GODOT_SHADER.encode()),
              (f"{src.asset}_minimap.tscn", godot_scene(src).encode())]
    note = (f"- {src.asset}_minimap.tscn: TextureRect hiện Minimap/{n['map']}"
            + (" qua shader minimap_circle.gdshader (mask tròn, viền rim)" if (src.minimap or {}).get("shape") ==
               "circle" else "") + f"; đặt trong CanvasLayer. POI ở Minimap/{n['json']} (x/y 0–1 từ góc trên-trái).")
    return files, [note]
