"""Minimap export (op.minimap_finish): map texture + POI JSON, a Unity uGUI prefab (Image + Mask with the circle sprite,
RawImage child showing the map) and a Godot TextureRect scene with a circle-mask canvas shader."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from studio_core.export.source import Files, Source

# com.unity.ugui script GUIDs (identical in every Unity version that ships uGUI as a package, 2019.2 → 6000.x).
UGUI_IMAGE = "fe87c0e1cc204ed48ad3b37840f39efc"
UGUI_RAW_IMAGE = "1344c3c82d62a2a41a3576d8abb8e3ea"
UGUI_MASK = "31a19414c41e5ae4aae2af33fee712f6"
SPRITE_SINGLE_ID = 21300000
TEXTURE_ID = 2800000
UI_LAYER = 5
GODOT_SHADER = """shader_type canvas_item;
// Generated by AI Asset Studio: round minimap mask with a soft edge and an optional rim.
uniform float radius : hint_range(0.0, 0.5) = 0.5;
uniform float feather : hint_range(0.0, 0.1) = 0.006;
uniform float rim : hint_range(0.0, 0.1) = 0.0;
uniform vec4 rim_color : source_color = vec4(0.12, 0.1, 0.13, 1.0);

void fragment() {
	float d = distance(UV, vec2(0.5));
	vec4 c = texture(TEXTURE, UV);
	c.rgb = mix(c.rgb, rim_color.rgb, smoothstep(radius - rim - feather, radius - rim, d) * step(0.0001, rim));
	c.a *= 1.0 - smoothstep(radius - feather, radius, d);
	COLOR = c;
}
"""


def minimap_set(step: Any, blobs: Any) -> tuple[dict[str, Any] | None, dict[str, Path]]:
    """minimap.json and its images, also when a gate passed it through under another port name."""
    from studio_core.ops.minimap import MINIMAP_FILE, MINIMAP_TYPE

    for refs in step.outputs.values():
        for ref in refs:
            if (ref.name or "") != MINIMAP_FILE:
                continue
            try:
                doc = json.loads(blobs.path(ref.hash).read_bytes())
                if doc.get("type") != MINIMAP_TYPE:
                    return None, {}
                files = {k: blobs.path(str(doc[k]["hash"])) for k in ("map", "mask", "framed")}
                if not all(p.is_file() for p in files.values()):
                    return None, {}
                return doc, files
            except (OSError, ValueError, KeyError, TypeError):
                return None, {}
    return None, {}


def _names(src: Source) -> dict[str, str]:
    a = src.asset
    return {"map": f"{a}_minimap.png", "mask": f"{a}_minimap_mask.png", "framed": f"{a}_minimap_framed.png",
            "json": f"{a}_minimap.json"}


def index_json(src: Source) -> bytes:
    doc = dict(src.minimap or {})
    n = _names(src)
    for k in ("map", "mask", "framed"):
        if isinstance(doc.get(k), dict):
            doc[k] = {"file": n[k]}
    doc["asset"] = src.asset
    return json.dumps(doc, indent=1, ensure_ascii=False).encode()


def _display(src: Source) -> int:
    return min(int((src.minimap or {}).get("size", [256])[0]), 256)


def _go(go: int, comps: list[int], name: str) -> str:
    lines = "".join(f"  - component: {{fileID: {c}}}\n" for c in comps)
    return f"""--- !u!1 &{go}
GameObject:
  m_ObjectHideFlags: 0
  m_CorrespondingSourceObject: {{fileID: 0}}
  m_PrefabInstance: {{fileID: 0}}
  m_PrefabAsset: {{fileID: 0}}
  serializedVersion: 6
  m_Component:
{lines}  m_Layer: {UI_LAYER}
  m_Name: {name}
  m_TagString: Untagged
  m_Icon: {{fileID: 0}}
  m_NavMeshLayer: 0
  m_StaticEditorFlags: 0
  m_IsActive: 1
"""


def _rect(rt: int, go: int, children: list[int], father: int, stretch: bool, size: int) -> str:
    kids = "[]" if not children else "\n" + "".join(f"  - {{fileID: {c}}}\n" for c in children).rstrip("\n")
    lo, hi, sd = ((0, 0), (1, 1), (0, 0)) if stretch else ((0.5, 0.5), (0.5, 0.5), (size, size))
    return f"""--- !u!224 &{rt}
RectTransform:
  m_ObjectHideFlags: 0
  m_CorrespondingSourceObject: {{fileID: 0}}
  m_PrefabInstance: {{fileID: 0}}
  m_PrefabAsset: {{fileID: 0}}
  m_GameObject: {{fileID: {go}}}
  m_LocalRotation: {{x: 0, y: 0, z: 0, w: 1}}
  m_LocalPosition: {{x: 0, y: 0, z: 0}}
  m_LocalScale: {{x: 1, y: 1, z: 1}}
  m_ConstrainProportionsScale: 0
  m_Children: {kids}
  m_Father: {{fileID: {father}}}
  m_LocalEulerAnglesHint: {{x: 0, y: 0, z: 0}}
  m_AnchorMin: {{x: {lo[0]}, y: {lo[1]}}}
  m_AnchorMax: {{x: {hi[0]}, y: {hi[1]}}}
  m_AnchoredPosition: {{x: 0, y: 0}}
  m_SizeDelta: {{x: {sd[0]}, y: {sd[1]}}}
  m_Pivot: {{x: 0.5, y: 0.5}}
"""


