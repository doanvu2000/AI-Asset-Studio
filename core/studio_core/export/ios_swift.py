"""Swift / Info.plist text for the iOS export: asset constants, nine-slice insets, SwiftUI animation + parallax views."""
from __future__ import annotations

import re

SWIFT_KEYWORDS = frozenset(
    "associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private "
    "precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue default "
    "defer do else fallthrough for guard if in repeat return throw switch where while any as await false is nil self "
    "super throws true try Type Protocol Self".split())
GEN_HEAD = "// GENERATED by AI Asset Studio. Edit the source asset instead.\n"
_TOKEN = re.compile(r"[A-Za-z0-9]+")


def _camel(text: str) -> str:
    toks = _TOKEN.findall(text) or ["asset"]
    out = toks[0][0].lower() + toks[0][1:] + "".join(t[0].upper() + t[1:] for t in toks[1:])
    return f"a{out[0].upper()}{out[1:]}" if out[0].isdigit() else out


def swift_names(values: list[str]) -> list[str]:
    """One valid, unique lowerCamelCase identifier per value; keywords get an `Asset` suffix."""
    taken: set[str] = set()
    out: list[str] = []
    for v in values:
        base = _camel(v)
        if base in SWIFT_KEYWORDS:
            base += "Asset"
        name, n = base, 2
        while name in taken:
            name, n = f"{base}{n}", n + 1
        taken.add(name)
        out.append(name)
    return out


def _q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def assets_swift(values: list[str]) -> str:
    lines = [f"    static let {n} = {_q(v)}" for n, v in zip(swift_names(values), values)]
    return GEN_HEAD + "import Foundation\n\nenum AssetStudioAssets {\n" + "\n".join(lines) + "\n}\n"


def _num(x: float) -> str:
    return f"{x:g}"


def nine_slices_swift(slices: list[tuple[str, tuple[int, int, int, int]]]) -> str:
    """slices: (image name, (left, top, right, bottom) cap insets in points, i.e. the 1x image's pixels)."""
    names = swift_names([n for n, _ in slices])
    lines = [f"    static let {n} = EdgeInsets(top: {_num(t)}, leading: {_num(l)}, bottom: {_num(b)}, trailing: {_num(r)})"
             for n, (_, (l, t, r, b)) in zip(names, slices)]
    return "enum AssetStudioNineSlices {\n" + "\n".join(lines) + "\n}\n"


def parallax_swift(sets: list[tuple[str, list[tuple[str, float]]]]) -> str:
    names = swift_names([a for a, _ in sets])
    out = ["enum AssetStudioParallaxSets {"]
    for n, (_, layers) in zip(names, sets):
        items = ",\n".join(f"        AssetStudioParallaxLayer(name: {_q(img)}, factor: {_num(f)})" for img, f in layers)
        out.append(f"    static let {n} = [\n{items}\n    ]")
    return "\n".join(out) + "\n}\n"


NINE_VIEW = """struct NineSliceImage: View {
    let name: String
    let insets: EdgeInsets
    var pixelArt = false

    var body: some View {
        Image(name)
            .resizable(capInsets: insets, resizingMode: .stretch)
            .interpolation(pixelArt ? .none : .high)
    }
}
"""

ANIM_VIEW = """struct AssetStudioClip: Decodable {
    let name: String
    let fps: Double
    let loop: Bool
    let frames: [String]
}

struct AssetStudioAnimationSet: Decodable {
    let atlas: String
    let pixel: Bool
    let frameSize: [Int]
    let clips: [AssetStudioClip]

    static func load(_ resource: String, bundle: Bundle = .main) -> AssetStudioAnimationSet? {
        guard let url = bundle.url(forResource: resource, withExtension: "json"),
              let data = try? Data(contentsOf: url) else { return nil }
        return try? JSONDecoder().decode(AssetStudioAnimationSet.self, from: data)
    }
}

final class AssetStudioFrames {
    let set: AssetStudioAnimationSet
    private let textures: [String: SKTexture]

    init?(resource: String, bundle: Bundle = .main) {
        guard let set = AssetStudioAnimationSet.load(resource, bundle: bundle) else { return nil }
        let atlas = SKTextureAtlas(named: set.atlas)
        var textures: [String: SKTexture] = [:]
        for name in set.clips.flatMap({ $0.frames }) { textures[name] = atlas.textureNamed(name) }
        self.set = set
        self.textures = textures
    }

    func image(clip: String, at time: TimeInterval, loop: Bool? = nil) -> Image? {
        guard let c = set.clips.first(where: { $0.name == clip }), !c.frames.isEmpty else { return nil }
        let step = Int(max(0, time) * max(c.fps, 0.001))
        let index = (loop ?? c.loop) ? step % c.frames.count : min(step, c.frames.count - 1)
        guard let texture = textures[c.frames[index]] else { return nil }
        return Image(decorative: texture.cgImage(), scale: 1)
    }
}

struct AssetStudioAnimation: View {
    let clip: String
    let resource: String
    let loop: Bool?
    @State private var frames: AssetStudioFrames?
    @State private var start = Date()

    init(clip: String, resource: String, loop: Bool? = nil) {
        self.clip = clip
        self.resource = resource
        self.loop = loop
    }

    var body: some View {
        TimelineView(.animation) { context in
            if let frames, let image = frames.image(clip: clip, at: context.date.timeIntervalSince(start), loop: loop) {
                image
                    .resizable()
                    .interpolation(frames.set.pixel ? .none : .high)
                    .aspectRatio(contentMode: .fit)
            }
        }
        .onAppear {
            if frames == nil { frames = AssetStudioFrames(resource: resource) }
            start = Date()
        }
    }
}
"""

PARALLAX_VIEW = """struct AssetStudioParallaxLayer: Identifiable {
    let name: String
    let factor: CGFloat
    var id: String { name }
}

struct AssetStudioParallax: View {
    let layers: [AssetStudioParallaxLayer]
    var offset: CGFloat

    var body: some View {
        GeometryReader { geo in
            ZStack(alignment: .topLeading) {
                ForEach(layers) { layer in
                    HStack(spacing: 0) {
                        Image(layer.name).resizable().frame(width: geo.size.width, height: geo.size.height)
                        Image(layer.name).resizable().frame(width: geo.size.width, height: geo.size.height)
                    }
                    .offset(x: -Self.wrap(offset * layer.factor, geo.size.width))
                }
            }
            .frame(width: geo.size.width, height: geo.size.height, alignment: .topLeading)
            .clipped()
        }
    }

    private static func wrap(_ value: CGFloat, _ width: CGFloat) -> CGFloat {
        guard width > 0 else { return 0 }
        let m = value.truncatingRemainder(dividingBy: width)
        return m < 0 ? m + width : m
    }
}
"""


def kit_swift(nine: str, anim: bool, parallax: str) -> str:
    """`AssetStudioKit.swift`: only the views the export needs; `nine` / `parallax` are the generated constant enums."""
    parts = [GEN_HEAD, "import SwiftUI\n"]
    if anim:
        parts.append("import SpriteKit\n")
    parts.append("")
    if nine:
        parts += [NINE_VIEW, nine]
    if anim:
        parts.append(ANIM_VIEW)
    if parallax:
        parts += [PARALLAX_VIEW, parallax]
    return "\n".join(parts)


def plist_fonts_snippet(font_files: list[str]) -> str:
    items = "\n".join(f"    <string>{f}</string>" for f in font_files)
    return f"<key>UIAppFonts</key>\n<array>\n{items}\n</array>\n"
