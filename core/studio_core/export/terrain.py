GODOT_SHADER = """shader_type spatial;
// Generated by AI Asset Studio: 4-layer splat terrain (R ground, G shore, B cliff, A peak). Layers tile in metres
// across the terrain; the cliff layer is sampled triplanar so steep faces do not stretch.

uniform sampler2D splat : hint_default_black, filter_linear, repeat_disable;
uniform sampler2D albedo_ground : source_color, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D albedo_shore : source_color, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D albedo_cliff : source_color, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D albedo_peak : source_color, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D normal_ground : hint_normal, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D normal_shore : hint_normal, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D normal_cliff : hint_normal, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D normal_peak : hint_normal, filter_linear_mipmap_anisotropic, repeat_enable;
uniform sampler2D rough_ground : hint_default_white, filter_linear_mipmap, repeat_enable;
uniform sampler2D rough_shore : hint_default_white, filter_linear_mipmap, repeat_enable;
uniform sampler2D rough_cliff : hint_default_white, filter_linear_mipmap, repeat_enable;
uniform sampler2D rough_peak : hint_default_white, filter_linear_mipmap, repeat_enable;
uniform vec4 tile_m = vec4(10.0, 8.0, 16.0, 12.0);
uniform float world_size = 1024.0;

varying vec3 tpos;
varying vec3 tnrm;

void vertex() {
	tpos = vec3(UV.x * world_size, VERTEX.y, UV.y * world_size);
	tnrm = NORMAL;
}

vec3 cliff_albedo(vec3 w) {
	return texture(albedo_cliff, tpos.zy / tile_m.z).rgb * w.x + texture(albedo_cliff, tpos.xz / tile_m.z).rgb * w.y
		+ texture(albedo_cliff, tpos.xy / tile_m.z).rgb * w.z;
}

float cliff_rough(vec3 w) {
	return texture(rough_cliff, tpos.zy / tile_m.z).r * w.x + texture(rough_cliff, tpos.xz / tile_m.z).r * w.y
		+ texture(rough_cliff, tpos.xy / tile_m.z).r * w.z;
}

void fragment() {
	vec4 s = texture(splat, UV);
	s /= max(s.r + s.g + s.b + s.a, 1e-4);
	vec2 p = tpos.xz;
	vec3 w = pow(abs(normalize(tnrm)), vec3(4.0));
	w /= w.x + w.y + w.z;
	ALBEDO = texture(albedo_ground, p / tile_m.x).rgb * s.r + texture(albedo_shore, p / tile_m.y).rgb * s.g
		+ cliff_albedo(w) * s.b + texture(albedo_peak, p / tile_m.w).rgb * s.a;
	NORMAL_MAP = texture(normal_ground, p / tile_m.x).rgb * s.r + texture(normal_shore, p / tile_m.y).rgb * s.g
		+ texture(normal_cliff, p / tile_m.z).rgb * s.b + texture(normal_peak, p / tile_m.w).rgb * s.a;
	ROUGHNESS = texture(rough_ground, p / tile_m.x).r * s.r + texture(rough_shore, p / tile_m.y).r * s.g
		+ cliff_rough(w) * s.b + texture(rough_peak, p / tile_m.w).r * s.a;
}
"""


GODOT_WATER_SHADER = """shader_type spatial;
render_mode blend_mix, depth_draw_opaque, cull_disabled;
// Generated by AI Asset Studio: plain water for the sea plane and the lakes / rivers mesh — tinted and see-through,
// two scrolling sine sets ripple the normal, more opaque at grazing angles.

uniform vec4 color : source_color = vec4(0.12, 0.32, 0.45, 0.72);
uniform float wave_scale = 0.08;
uniform float wave_speed = 0.6;
uniform float ripple = 0.2;

void fragment() {
	vec3 w = (INV_VIEW_MATRIX * vec4(VERTEX, 1.0)).xyz;
	vec2 p = w.xz * wave_scale;
	float t = TIME * wave_speed;
	vec2 d = vec2(cos(p.x * 3.1 + t) + cos(p.y * 2.3 - t * 0.8), sin(p.y * 2.7 + t * 1.1) + sin(p.x * 1.9 - t * 0.7));
	NORMAL_MAP = vec3(d * ripple * 0.25 + 0.5, 1.0);
	ALBEDO = color.rgb;
	ROUGHNESS = 0.06;
	SPECULAR = 0.7;
	float fres = pow(1.0 - clamp(dot(NORMAL, VIEW), 0.0, 1.0), 4.0);
	ALPHA = mix(color.a, 1.0, fres * 0.6);
}
"""


def _water_material() -> str:
    return ('[gd_resource type="ShaderMaterial" load_steps=2 format=3]\n\n'
            '[ext_resource type="Shader" path="asset_studio_water.gdshader" id="1_shader"]\n\n'
            '[resource]\nshader = ExtResource("1_shader")\n')


def _g(v: float) -> str:
    return f"{v:.6g}"


def _material(src: Source) -> str:
    from studio_core.ops.terrain import ROLES

    a, t = src.asset, src.terrain or {}
    ext = ['[ext_resource type="Shader" path="asset_studio_terrain.gdshader" id="1_shader"]',
           f'[ext_resource type="Texture2D" path="{a}_splat.png" id="2_splat"]']
    props = ['shader = ExtResource("1_shader")', 'shader_parameter/splat = ExtResource("2_splat")']
    i = 3
    tiles = []
    for lay in _layers(src):
        role = lay["role"]
        tiles.append(float(lay["tile_m"]))
        for m, prop in (("albedo", "albedo"), ("normal", "normal"), ("roughness", "rough")):
            rid = f"{i}_{role}_{m}"
            ext.append(f'[ext_resource type="Texture2D" path="Layers/{a}_{role}_{m}.png" id="{rid}"]')
            props.append(f'shader_parameter/{prop}_{role} = ExtResource("{rid}")')
            i += 1
    tiles += [10.0] * (len(ROLES) - len(tiles))
    props += [f"shader_parameter/tile_m = Vector4({', '.join(_g(x) for x in tiles)})",
              f"shader_parameter/world_size = {_g(float(t['world_m']))}"]
    return (f'[gd_resource type="ShaderMaterial" load_steps={len(ext) + 1} format=3]\n\n' + "\n".join(ext)
            + "\n\n[resource]\n" + "\n".join(props) + "\n")


def _scene(src: Source) -> str:
    from studio_core.export.skybox import _basis_for

    a, t = src.asset, src.terrain or {}
    world, height = float(t["world_m"]), float(t["height_m"])
    water = _water_m(src)
    sky = bool(src.skybox and src.skybox_files)
    wb = _bodies(src)
    ext = ['[ext_resource type="Script" path="Terrain/asset_studio_terrain.gd" id="1_script"]',
           f'[ext_resource type="Material" path="Terrain/{a}_terrain_material.tres" id="2_material"]']
    if sky:
        ext.append(f'[ext_resource type="Environment" path="Skybox/{a}_environment.tres" id="3_env"]')
    if water is not None or wb:
        ext.append(f'[ext_resource type="Material" path="Terrain/{a}_water_material.tres" id="4_water"]')
    subs: list[str] = []
    if not sky:
        subs += ['[sub_resource type="ProceduralSkyMaterial" id="ProceduralSkyMaterial_1"]',
                 '[sub_resource type="Sky" id="Sky_1"]\nsky_material = SubResource("ProceduralSkyMaterial_1")',
                 '[sub_resource type="Environment" id="Environment_1"]\nbackground_mode = 2\nsky = SubResource("Sky_1")\n'
                 'ambient_light_source = 3\nambient_light_energy = 0.6\nreflected_light_source = 2']
    if water is not None:
        subs += [f'[sub_resource type="PlaneMesh" id="PlaneMesh_water"]\nmaterial = ExtResource("4_water")\n'
                 f'size = Vector2({_g(world)}, {_g(world)})']
    sun_dir = (-0.45, 0.72, 0.53)
    light = (src.skybox or {}).get("light") or {}
    if sky and light.get("distinct") and len(light.get("dir") or []) == 3:
        d = light["dir"]
        # Same flip as the skybox scene: the panorama centre sits at Godot's -Z.
        sun_dir = (float(d[0]), float(d[1]), -float(d[2]))
    n = math.sqrt(sum(c * c for c in sun_dir)) or 1.0
    sun = ", ".join(_g(v) for v in _basis_for(tuple(c / n for c in sun_dir)))  # type: ignore[arg-type]
    cam_pos = (-0.55 * world, height + 0.3 * world, 0.55 * world)
    back = (cam_pos[0], cam_pos[1] - height * 0.25, cam_pos[2])
    bn = math.sqrt(sum(c * c for c in back)) or 1.0
    cam = ", ".join(_g(v) for v in _basis_for(tuple(c / bn for c in back)))  # type: ignore[arg-type]
    nodes = [f'[node name="{a}" type="Node3D"]',
             f'[node name="Terrain" type="Node3D" parent="."]\nscript = ExtResource("1_script")\n'
             f'heightmap_file = "{a}_height.r32"\nresolution = {int(t["resolution"])}\nworld_size = {_g(world)}\n'
             f'height_scale = {_g(height)}\nmaterial = ExtResource("2_material")'
             + (f'\nwater_file = "{a}_water.raw"\nwater_resolution = {int(wb["resolution"])}\n'
                'water_material = ExtResource("4_water")' if wb else "")]
    if water is not None:
        nodes.append(f'[node name="Water" type="MeshInstance3D" parent="."]\n'
                     f'transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, {_g(water)}, 0)\n'
                     'mesh = SubResource("PlaneMesh_water")')
    nodes += [f'[node name="WorldEnvironment" type="WorldEnvironment" parent="."]\n'
              f'environment = {"ExtResource(\"3_env\")" if sky else "SubResource(\"Environment_1\")"}',
              f'[node name="Sun" type="DirectionalLight3D" parent="."]\ntransform = Transform3D({sun}, 0, {_g(height * 2)}, 0)\n'
              'shadow_enabled = true\ndirectional_shadow_max_distance = ' + _g(min(world, 2000.0)),
              f'[node name="Camera3D" type="Camera3D" parent="."]\n'
              f'transform = Transform3D({cam}, {_g(cam_pos[0])}, {_g(cam_pos[1])}, {_g(cam_pos[2])})\n'
              f'far = {_g(world * 3)}']
    head = f"[gd_scene load_steps={len(ext) + len(subs) + 1} format=3]"
    return "\n\n".join([head, "\n".join(ext), *subs, *nodes]) + "\n"


def godot_files(src: Source) -> tuple[Files, list[str]]:
    a, fl, t = src.asset, src.terrain_files, src.terrain or {}
    files: Files = [(f"Terrain/{a}_height.r32", r32(fl["raw"])), (f"Terrain/{a}_height.raw", fl["raw"]),
                    (f"Terrain/{a}_height16.png", fl["heightmap"]), (f"Terrain/{a}_splat.png", fl["splat"]),
                    # Lossless, no mipmaps and no alpha-border fix: the splat's RGBA are weights, not colours.
                    (f"Terrain/{a}_splat.png.import", godot_import(mipmaps=False, fix_alpha=False))]
    for lay in _layers(src):
        role = lay["role"]
        for m in LAYER_MAPS:
            rel = f"Terrain/Layers/{a}_{role}_{m}.png"
            files += [(rel, fl[f"{role}_{m}"]), (f"{rel}.import", godot_import(normal=m == "normal"))]
    files += [("Terrain/asset_studio_terrain.gd", GODOT_SCRIPT.encode()),
              ("Terrain/asset_studio_terrain.gdshader", GODOT_SHADER.encode()),
              (f"Terrain/{a}_terrain_material.tres", _material(src).encode()),
              (f"{a}_terrain.tscn", _scene(src).encode())]
    wb = _bodies(src)
    if wb:
        files.append((f"Terrain/{a}_water.raw", fl["water"]))
    if wb or _water_m(src) is not None:
        files += [("Terrain/asset_studio_water.gdshader", GODOT_WATER_SHADER.encode()),
                  (f"Terrain/{a}_water_material.tres", _water_material().encode())]
    n = t.get("resolution")
    notes = [f"- {a}_terrain.tscn: node Terrain (Terrain/asset_studio_terrain.gd) tự dựng mesh chia chunk 128 ô, 3 mức "
             "LOD theo visibility range (có viền chống hở), shader splat 4 lớp (nền, ven nước, vách đá — chiếu "
             "triplanar, đỉnh) và StaticBody3D + HeightMapShape3D khi mở scene; height_at(x, z) trả độ cao. "
             + ("Có mặt biển (MeshInstance3D Water, shader asset_studio_water.gdshader). "
                if _water_m(src) is not None else "")
             + (_bodies_note(src).replace("mesh nước riêng", "mesh nước riêng (node con WaterBodies)") if wb else "")
             + ("WorldEnvironment lấy skybox trong Skybox/. " if src.skybox else ""),
             f"- Terrain/{a}_height.r32 (float32 0..1, {n}×{n})"
             + (f" và {a}_water.raw" if wb else "")
             + " là dữ liệu script đọc: khi export game thêm `*.r32"
             + (", *.raw" if wb else "")
             + "` vào Export > Resources > Filters to export non-resource files. "
             f"{a}_height.raw (16-bit LE, hàng đầu = mép bắc) và {a}_height16.png cho engine / tool khác."]
    return files, notes
