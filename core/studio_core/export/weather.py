GODOT_MIST_SHADER = """shader_type canvas_item;
// Generated by AI Asset Studio: scrolling mist. `scroll` is in tiles per second and a whole number of tiles per loop,
// so the drift repeats exactly; ground_fade 1 thickens the mist toward the bottom of the screen.

uniform sampler2D mist_tex : source_color, filter_linear, repeat_enable;
uniform vec4 tint : source_color = vec4(0.87, 0.91, 0.95, 1.0);
uniform float density : hint_range(0.0, 1.0) = 1.0;
uniform vec2 tiles = vec2(2.0, 1.125);
uniform vec2 scroll = vec2(0.0625, 0.0);
uniform float ground_fade : hint_range(0.0, 1.0) = 0.0;

void fragment() {
	vec2 uv = UV * tiles + scroll * TIME;
	float a = texture(mist_tex, uv).a * density;
	float ramp = mix(1.0, smoothstep(0.0, 1.0, UV.y), ground_fade);
	COLOR = vec4(tint.rgb, a * ramp * tint.a);
}
"""

