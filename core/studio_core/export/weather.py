def weather_set(step: Any, blobs: Any) -> tuple[dict[str, Any] | None, dict[str, Path]]:
    """weather.json and its textures, also when a gate passed it through under another port name."""
    from studio_core.ops.weather import WEATHER_FILE, WEATHER_TYPE

    for refs in step.outputs.values():
        for ref in refs:
            if (ref.name or "") != WEATHER_FILE:
                continue
            try:
                doc = json.loads(blobs.path(ref.hash).read_bytes())
                if doc.get("type") != WEATHER_TYPE or not doc.get("layers"):
                    return None, {}
                files = {k: blobs.path(str(t["hash"])) for k, t in doc["textures"].items()}
                if not all(p.is_file() for p in files.values()):
                    return None, {}
                return doc, files
            except (OSError, ValueError, KeyError, TypeError, AttributeError):
                return None, {}
    return None, {}


def _doc(src: Source) -> tuple[dict[str, Any], dict[str, Path]]:
    return getattr(src, "weather", None) or {}, getattr(src, "weather_files", None) or {}


def _gd(v: float) -> str:
    return f"{float(v):.6g}"


def _hex_alpha(color: str, alpha: float) -> str:
    return color[:7] + f"{int(round(max(0.0, min(1.0, alpha)) * 255)):02x}"


def _tex_name(a: str, key: str) -> str:
    return f"{a}_{key}.png"


def _emitters(doc: dict[str, Any]) -> list[dict[str, Any]]:
    return [la for la in doc["layers"] if la.get("emitter")]


def _ramp(em: dict[str, Any]) -> list[list[Any]]:
    c, a = em["color"], em["alpha"]
    if em["spawn"] == "top":
        return [[0, _hex_alpha(c, 0)], [0.04, _hex_alpha(c, a)], [0.96, _hex_alpha(c, a)], [1, _hex_alpha(c, 0)]]
    return [[0, _hex_alpha(c, 0)], [0.2, _hex_alpha(c, a)], [0.8, _hex_alpha(c, a)], [1, _hex_alpha(c, 0)]]


def godot_particles_scene(a: str, layer: dict[str, Any], tex_px: int, tex_file: str) -> str:
    from studio_core.export.vfx_particles import _sub_gradient

    em = layer["emitter"]
    w, h = layer["area"]
    cx, cy, ex, ey = em["box"]
    lo, hi = em["speed"]
    k = 1 / max(tex_px, 1)
    ppm = ['[sub_resource type="ParticleProcessMaterial" id="ppm"]', "particle_flag_disable_z = true"]
    if em["align_velocity"]:
        ppm.append("particle_flag_align_y = true")
    ppm += ["emission_shape = 3", f"emission_box_extents = Vector3({_gd(ex)}, {_gd(ey)}, 1)",
            f"direction = Vector3({_gd(em['direction'][0])}, {_gd(em['direction'][1])}, 0)",
            f"spread = {_gd(em['spread'])}", f"initial_velocity_min = {_gd(lo)}", f"initial_velocity_max = {_gd(hi)}",
            "gravity = Vector3(0, 0, 0)", f"scale_min = {_gd(em['quad_px'][0] * k)}",
            f"scale_max = {_gd(em['quad_px'][1] * k)}", 'color_ramp = SubResource("ramp_tex")']
    if em["random_angle"]:
        ppm += ["angle_min = 0.0", "angle_max = 360.0"]
    if em["spin"][1] > 0:
        ppm += [f"angular_velocity_min = {_gd(em['spin'][0])}", f"angular_velocity_max = {_gd(em['spin'][1])}"]
    if em["turbulence"] > 0:
        ppm += ["turbulence_enabled = true", f"turbulence_noise_strength = {_gd(em['turbulence'])}",
                "turbulence_noise_scale = 6.0"]
    mat = (f'[sub_resource type="CanvasItemMaterial" id="mat"]\nblend_mode = {1 if em["blend"] == "add" else 0}\n\n'
           if em["blend"] == "add" else "")
    reach = max(w, h) + em["margin"] * 2 + 200
    node = ['[node name="Particles" type="GPUParticles2D" parent="."]', *(['material = SubResource("mat")'] if mat else []),
            f"position = Vector2({_gd(cx)}, {_gd(cy)})", f"amount = {em['amount']}", 'texture = ExtResource("1_tex")',
            f"lifetime = {_gd(em['lifetime'])}", f"preprocess = {_gd(em['lifetime'])}",
            f"visibility_rect = Rect2({_gd(-reach)}, {_gd(-reach)}, {_gd(2 * reach)}, {_gd(2 * reach)})",
            "local_coords = false", 'process_material = SubResource("ppm")']
    return ("[gd_scene format=3]\n\n" + f'[ext_resource type="Texture2D" path="Textures/{tex_file}" id="1_tex"]\n\n'
            + _sub_gradient("ramp", _ramp(em)) + "\n".join(ppm) + "\n\n" + mat
            + f'[node name="{a}_{layer["name"]}" type="CanvasLayer"]\nlayer = {GODOT_LAYER["particles"]}\n\n'
            + "\n".join(node) + "\n")


def godot_mist_scene(a: str, layer: dict[str, Any], tex_file: str, shader_file: str) -> str:
    return ("[gd_scene format=3]\n\n"
            f'[ext_resource type="Texture2D" path="Textures/{tex_file}" id="1_tex"]\n'
            f'[ext_resource type="Shader" path="{shader_file}" id="2_shader"]\n\n'
            '[sub_resource type="ShaderMaterial" id="fog_mat"]\nshader = ExtResource("2_shader")\n'
            'shader_parameter/mist_tex = ExtResource("1_tex")\n'
            f'shader_parameter/tint = Color({", ".join(_gd(c) for c in _rgb(layer["tint"]))}, 1)\n'
            "shader_parameter/density = 1.0\n"
            f'shader_parameter/tiles = Vector2({_gd(layer["tiles"][0])}, {_gd(layer["tiles"][1])})\n'
            f'shader_parameter/scroll = Vector2({_gd(layer["scroll"][0])}, {_gd(layer["scroll"][1])})\n'
            f'shader_parameter/ground_fade = {_gd(layer["ground_fade"])}\n\n'
            f'[node name="{a}_mist" type="CanvasLayer"]\nlayer = {GODOT_LAYER["mist"]}\n\n'
            '[node name="Fog" type="ColorRect" parent="."]\nmaterial = SubResource("fog_mat")\nlayout_mode = 3\n'
            "anchors_preset = 15\nanchor_right = 1.0\nanchor_bottom = 1.0\ngrow_horizontal = 2\ngrow_vertical = 2\n"
            "mouse_filter = 2\n")


def _rgb(h: str) -> tuple[float, float, float]:
    s = h.lstrip("#")
    return tuple(int(s[i:i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore[return-value]


def godot_demo_scene(a: str, names: list[str]) -> str:
    ext = [f'[ext_resource type="PackedScene" path="{a}_{n}.tscn" id="{i + 1}_{n}"]' for i, n in enumerate(names)]
    nodes = [f'[node name="{n}" parent="." instance=ExtResource("{i + 1}_{n}")]' for i, n in enumerate(names)]
    return ("[gd_scene format=3]\n\n" + "\n".join(ext) + f'\n\n[node name="{a}_weather_demo" type="Node2D"]\n\n'
            + "\n\n".join(nodes) + "\n")


def godot_files(src: Source) -> tuple[Files, list[str]]:
    doc, paths = _doc(src)
    a = src.asset
    if not doc or not paths:
        return [], []
    files: Files = [(f"Weather/Textures/{_tex_name(a, k)}", p) for k, p in paths.items()]
    area = doc["area"]
    names: list[str] = []
    for la in doc["layers"]:
        la = {**la, "area": area}
        if la["kind"] == "mist":
            shader = f"{a}_mist.gdshader"
            files += [(f"Weather/{shader}", GODOT_MIST_SHADER.encode()),
                      (f"Weather/{a}_mist.tscn", godot_mist_scene(a, la, _tex_name(a, "mist"), shader).encode())]
            names.append("mist")
        elif la.get("emitter"):
            tex = la["emitter"]["texture"]
            px = int(doc["textures"][tex]["size"][0])
            files.append((f"Weather/{a}_{la['name']}.tscn",
                          godot_particles_scene(a, la, px, _tex_name(a, tex)).encode()))
            names.append(la["name"])
    doc_out = {k: v for k, v in doc.items() if k != "textures"}
    doc_out["textures"] = {k: {**{kk: vv for kk, vv in t.items() if kk != "hash"}, "file": f"Textures/{_tex_name(a, k)}"}
                           for k, t in doc["textures"].items()}
    files += [(f"Weather/{a}_weather_demo.tscn", godot_demo_scene(a, names).encode()),
              (f"Weather/{a}_weather.json", json.dumps(doc_out, indent=1, ensure_ascii=False).encode())]
    note = (f"- Weather/{a}_<lớp>.tscn: CanvasLayer (layer {GODOT_LAYER['particles']}, vẽ trên cả Parallax2D và "
            "nhân vật, không lệch theo camera) + GPUParticles2D dùng ParticleProcessMaterial: mưa/tuyết/lá/tro rơi từ mép "
            "trên màn hình (preprocess = đời hạt nên bật cảnh là đã đầy), đom đóm phủ cả màn hình. "
            f"{a}_mist.tscn: CanvasLayer (layer {GODOT_LAYER['mist']}) + ColorRect phủ màn hình, shader "
            f"{a}_mist.gdshader cuộn texture sương liền mạch (uniform scroll = số ô/giây, ground_fade 1 = đặc dần về đáy; "
            "đổi tint/density bằng set_shader_parameter). Mật độ bị chặn ở "
            f"{_max_amount()} hạt/lớp cho mobile. {a}_weather_demo.tscn gom mọi lớp. Textures/{a}_<lớp>_sheet.png là "
            "sheet loop liền (khung N = khung 0) cho engine không có particle; weather.json giữ số đo QA từng lớp.")
    return files, [note]


