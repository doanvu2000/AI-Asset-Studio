def unity_emitter(em: dict[str, Any], name: str, ppu: float) -> dict[str, Any]:
    """The weather emitter in the vfx preset schema so vfx_particles' ParticleSystem writer can be reused."""
    return {"name": name, "texture": em["texture"], "blend": em["blend"], "delay": 0.0, "burst": 0,
            "rate": em["amount"] / em["lifetime"], "lifetime": [em["lifetime"], em["lifetime"]], "speed": [0.0, 0.0],
            "shape": {"type": "point"}, "gravity": 0.0, "drag": 0.0,
            "size": [em["quad_px"][0] / ppu, em["quad_px"][1] / ppu], "size_curve": [[0, 1], [1, 1]],
            "rotation": [0, 360] if em["random_angle"] else [0, 0], "spin": em["spin"],
            "align": "velocity" if em["align_velocity"] else "billboard", "space": "local", "styled": False,
            "colors": _ramp(em)}


def unity_particle_doc(fid: int, go: int, em: dict[str, Any], name: str, ppu: float) -> str:
    """vfx_particles' ParticleSystem with its shape turned into a thin box over the spawn area and the direction and
    speed given by the velocity module (the vfx writer only knows point/sphere/circle/cone shapes)."""
    from studio_core.export.vfx_particles import _minmax, unity_particle_system

    e = unity_emitter(em, name, ppu)
    doc = unity_particle_system(fid, go, e, {"loop": True, "duration": float(em["lifetime"])}, root=True, demo=False)
    _, _, bx, by = em["box"]
    doc = doc.replace("    type: 0\n", "    type: 5\n", 1).replace(
        "    m_Scale: {x: 1, y: 1, z: 1}", f"    m_Scale: {{x: {_gd(2 * bx / ppu)}, y: {_gd(2 * by / ppu)}, z: 0.001}}", 1)
    dx, dy = em["direction"]
    lo, hi = (v / ppu for v in em["speed"])
    xs, ys = sorted((dx * lo, dx * hi)), sorted((-dy * lo, -dy * hi))
    velocity = (f"  VelocityModule:\n    enabled: 1\n{_minmax('x', '    ', xs[0], xs[1])}"
                f"{_minmax('y', '    ', ys[0], ys[1])}{_minmax('z', '    ', 0.0)}    inWorldSpace: 0\n")
    return doc.replace("  SizeModule:\n", velocity + "  SizeModule:\n", 1)


