"""SwiftUI Shader Pack: Metal ports of the Flutter .frag presets (shader_templates/metal/) as [[stitchable]] functions
plus View modifiers (iOS 17+). Identical for every asset, so a pack merge keeps one copy."""
from __future__ import annotations

from studio_core.export.shaders import template_dir
from studio_core.export.source import Files

METAL_IDS = ("hit_flash", "dissolve", "palette_swap", "outline_pulse", "water_ripple", "wind_sway")
METAL_FILE = "Sources/AssetStudioShaders.metal"
SWIFT_FILE = "Sources/AssetStudioShaderEffects.swift"

NOTE_METAL = """- Sources/AssetStudioShaders.metal + AssetStudioShaderEffects.swift: Shader Pack Metal cho SwiftUI (iOS 17+, thêm cả hai
  file vào target để .metal vào default library). View modifier: .hitFlash, .dissolve, .paletteSwap, .outlinePulse,
  .waterRipple, .windSway, ví dụ Image("sprite").hitFlash(color: .white, amount: flash). Uniform cùng tên/nghĩa như
  shaders/*.frag của Flutter (đơn vị là point thay vì pixel của sheet). Hiệu ứng chỉ vẽ trong khung view: thêm .padding
  quanh sprite cho outline/ripple/sway. Chưa biên dịch thật trên Xcode."""


def metal_source() -> str:
    root = template_dir() / "metal"
    parts = [(root / f"{n}.metal").read_text(encoding="utf-8").rstrip() for n in ("common", *METAL_IDS)]
    return "// Generated by AI Asset Studio.\n" + "\n\n".join(parts) + "\n"


def shader_files() -> tuple[Files, list[str]]:
    return [(METAL_FILE, metal_source().encode()), (SWIFT_FILE, SWIFT.encode())], [NOTE_METAL]


SWIFT = r'''import SwiftUI

@available(iOS 17, *)
private struct AssetStudioTimed<Result: View>: ViewModifier {
    let paused: Bool
    let build: (Content, Float) -> Result
    @State private var start = Date()

    func body(content: Content) -> some View {
        TimelineView(.animation(minimumInterval: nil, paused: paused)) { context in
            build(content, Float(context.date.timeIntervalSince(start)))
        }
    }
}

@available(iOS 17, *)
private func assetStudioPalette(_ palettes: [[Color]]) -> [Float] {
    let env = EnvironmentValues()
    return palettes.flatMap { stops in
        stops.flatMap { color -> [Float] in
            let c = color.resolve(in: env)
            return [c.red, c.green, c.blue]
        }
    }
}

@available(iOS 17, *)
public extension View {
    /// Flashes towards `color`; `amount` 0...1, or `speed` > 0 to blink on its own.
    func hitFlash(color: Color = .white, amount: Float = 0, speed: Float = 0) -> some View {
        modifier(AssetStudioTimed(paused: speed <= 0) { content, time in
            content.colorEffect(ShaderLibrary.assetStudioHitFlash(
                .float(time), .color(color), .float(amount), .float(speed)))
        })
    }

    /// Burns the view away with noise; `progress` 0...1, or `speed` > 0 to ping-pong on its own.
    func dissolve(progress: Float = 0, edgeColor: Color = Color(red: 1, green: 0.55, blue: 0.1), edgeWidth: Float = 0.06,
                  noiseScale: Float = 6, speed: Float = 0) -> some View {
        modifier(AssetStudioTimed(paused: speed <= 0) { content, time in
            content.colorEffect(ShaderLibrary.assetStudioDissolve(
                .float(time), .color(edgeColor), .float(progress), .float(edgeWidth), .float(noiseScale), .float(speed)))
        })
    }

    /// Each palette lists colour stops dark to light; a pixel's luma picks the colour from `row`.
    func paletteSwap(_ palettes: [[Color]], row: Int = 0, strength: Float = 1) -> some View {
        let flat = assetStudioPalette(palettes)
        return modifier(AssetStudioTimed(paused: true) { content, time in
            content.colorEffect(ShaderLibrary.assetStudioPaletteSwap(
                .float(time), .float(Float(row)), .float(Float(palettes.count)), .float(strength), .floatArray(flat)))
        })
    }

    /// `width` in points; the outline is clipped to the view, so pad the content by at least `width`.
    func outlinePulse(color: Color = Color(red: 1, green: 0.85, blue: 0.3), width: Float = 1, speed: Float = 1.5,
                      minAlpha: Float = 0.25) -> some View {
        modifier(AssetStudioTimed(paused: false) { content, time in
            content.layerEffect(
                ShaderLibrary.assetStudioOutlinePulse(
                    .boundingRect, .float(time), .color(color), .float(width), .float(speed), .float(minAlpha)),
                maxSampleOffset: CGSize(width: CGFloat(width), height: CGFloat(width)))
        })
    }

    func waterRipple(tint: Color = .white, amplitude: Float = 1.5, wavelength: Float = 12, speed: Float = 1) -> some View {
        modifier(AssetStudioTimed(paused: false) { content, time in
            content.layerEffect(
                ShaderLibrary.assetStudioWaterRipple(
                    .boundingRect, .float(time), .color(tint), .float(amplitude), .float(wavelength), .float(speed)),
                maxSampleOffset: CGSize(width: CGFloat(amplitude), height: 0))
        })
    }

    /// The foot (bottom of the view) stays fixed and the top sways by `strength` x height; `maxHeight` bounds the sample offset.
    func windSway(strength: Float = 0.06, speed: Float = 0.6, wave: Float = 0.02, worldX: Float = 0,
                  maxHeight: CGFloat = 256) -> some View {
        modifier(AssetStudioTimed(paused: false) { content, time in
            content.layerEffect(
                ShaderLibrary.assetStudioWindSway(
                    .boundingRect, .float(time), .float(strength), .float(speed), .float(wave), .float(worldX)),
                maxSampleOffset: CGSize(width: CGFloat(strength) * maxHeight, height: 0))
        })
    }
}
'''
