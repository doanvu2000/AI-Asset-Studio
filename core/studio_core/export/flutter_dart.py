"""Dart / pubspec text for the Flutter + Flame export: asset constants, the pubspec `flutter:` block, runtime helpers."""
from __future__ import annotations

import re
from pathlib import PurePosixPath

DART_KEYWORDS = frozenset(
    "abstract as assert async await break case catch class const continue covariant default deferred do dynamic else "
    "enum export extends extension external factory false final finally for function get hide if implements import in "
    "interface is late library mixin new null of on operator part required rethrow return set show static super "
    "switch sync this throw true try typedef var void when while with yield record sealed base".split())
DENSITY_DIRS = ("2.0x", "3.0x")
FONT_EXT = (".ttf", ".otf")
GEN_HEAD = "// GENERATED by AI Asset Studio. Edit the source asset instead.\n"
_TOKEN = re.compile(r"[A-Za-z0-9]+")


def is_density_variant(path: str) -> bool:
    return any(p in DENSITY_DIRS for p in PurePosixPath(path).parts)


def _camel(text: str) -> str:
    toks = _TOKEN.findall(text) or ["asset"]
    out = toks[0][0].lower() + toks[0][1:] + "".join(t[0].upper() + t[1:] for t in toks[1:])
    return f"a{out[0].upper()}{out[1:]}" if out[0].isdigit() else out


def dart_names(paths: list[str]) -> list[str]:
    """One valid, unique lowerCamelCase identifier per path (stem; then extension, parent dir, counter on clashes)."""
    taken: set[str] = set()
    out: list[str] = []
    for p in paths:
        pp = PurePosixPath(p)
        base = _camel(pp.stem)
        cands = [base, base + _camel(pp.suffix.lstrip(".")).capitalize() if pp.suffix else base,
                 _camel(f"{pp.parent.name}_{pp.stem}")]
        name = next((c for c in cands if c not in taken and c not in DART_KEYWORDS), None)
        n = 2
        while name is None:
            name = f"{base}{n}" if f"{base}{n}" not in taken else None
            n += 1
        taken.add(name)
        out.append(name)
    return out


def _q(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def asset_paths(paths: list[str]) -> list[str]:
    seen: dict[str, None] = {}
    for p in paths:
        if p.startswith("assets/") and not is_density_variant(p):
            seen.setdefault(p, None)
    return list(seen)


def assets_dart(paths: list[str], class_name: str = "AssetStudioAssets") -> str:
    """`lib/gen/asset_studio_assets.dart`: one `static const String` per asset (density variants are implicit)."""
    keep = asset_paths(paths)
    lines = [GEN_HEAD, f"class {class_name} {{", f"  {class_name}._();", ""]
    lines += [f"  static const String {n} = {_q(p)};" for n, p in zip(dart_names(keep), keep)]
    lines += ["}", ""]
    return "\n".join(lines)


def pubspec_snippet(paths: list[str]) -> str:
    """`flutter: assets:` lists every directory (Flutter does not recurse) plus `fonts:` for .ttf / .otf files."""
    keep = asset_paths(paths)
    dirs = list(dict.fromkeys(str(PurePosixPath(p).parent) + "/" for p in keep))
    lines = ["flutter:", "  assets:"] + [f"    - {d}" for d in dirs]
    fonts = [p for p in keep if p.lower().endswith(FONT_EXT)]
    if fonts:
        lines.append("  fonts:")
        families: dict[str, list[str]] = {}
        for p in fonts:
            families.setdefault(PurePosixPath(p).stem.split("-")[0] or "Font", []).append(p)
        for fam, items in families.items():
            lines += [f"    - family: {fam}", "      fonts:"] + [f"        - asset: {p}" for p in items]
    return "\n".join(lines) + "\n"


