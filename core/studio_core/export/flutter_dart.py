FLAME_FONT = """
class BitmapGlyph {
  const BitmapGlyph(this.x, this.y, this.w, this.h, this.xOffset, this.yOffset, this.xAdvance);

  final double x;
  final double y;
  final double w;
  final double h;
  final double xOffset;
  final double yOffset;
  final double xAdvance;
}

/// Draws AngelCode BMFont text from `assets/fonts/<name>_font.json` + `assets/images/fonts/<name>.png`.
class BitmapFont {
  BitmapFont(this.image, this.lineHeight, this.glyphs, this.kernings);

  final ui.Image image;
  final double lineHeight;
  final Map<int, BitmapGlyph> glyphs;
  final Map<int, double> kernings;

  static Future<BitmapFont> load(Images images, String name) async {
    final doc =
        jsonDecode(await rootBundle.loadString('assets/fonts/${name}_font.json'))
            as Map<String, dynamic>;
    final glyphs = <int, BitmapGlyph>{};
    for (final raw in doc['chars'] as List<dynamic>) {
      final c = raw as Map<String, dynamic>;
      double n(String k) => (c[k] as num).toDouble();
      glyphs[c['id'] as int] = BitmapGlyph(
        n('x'),
        n('y'),
        n('width'),
        n('height'),
        n('xoffset'),
        n('yoffset'),
        n('xadvance'),
      );
    }
    final kernings = <int, double>{};
    for (final raw in doc['kernings'] as List<dynamic>) {
      final k = raw as List<dynamic>;
      kernings[((k[0] as int) << 16) | (k[1] as int)] = (k[2] as num).toDouble();
    }
    return BitmapFont(
      await images.load('fonts/$name.png'),
      (doc['lineHeight'] as num).toDouble(),
      glyphs,
      kernings,
    );
  }

  double measure(String text, {double scale = 1}) {
    var width = 0.0;
    var line = 0.0;
    int? prev;
    for (final r in text.runes) {
      if (r == 0x0A) {
        width = line > width ? line : width;
        line = 0;
        prev = null;
        continue;
      }
      final g = glyphs[r];
      if (g == null) continue;
      line += (g.xAdvance + (kernings[((prev ?? 0) << 16) | r] ?? 0)) * scale;
      prev = r;
    }
    return line > width ? line : width;
  }

  void draw(
    ui.Canvas canvas,
    String text,
    ui.Offset topLeft, {
    double scale = 1,
    ui.Paint? paint,
  }) {
    final p = paint ?? (ui.Paint()..filterQuality = ui.FilterQuality.none);
    var x = topLeft.dx;
    var y = topLeft.dy;
    int? prev;
    for (final r in text.runes) {
      if (r == 0x0A) {
        x = topLeft.dx;
        y += lineHeight * scale;
        prev = null;
        continue;
      }
      final g = glyphs[r];
      if (g == null) continue;
      x += (kernings[((prev ?? 0) << 16) | r] ?? 0) * scale;
      canvas.drawImageRect(
        image,
        ui.Rect.fromLTWH(g.x, g.y, g.w, g.h),
        ui.Rect.fromLTWH(x + g.xOffset * scale, y + g.yOffset * scale, g.w * scale, g.h * scale),
        p,
      );
      x += g.xAdvance * scale;
      prev = r;
    }
  }
}

class BitmapTextComponent extends PositionComponent {
  BitmapTextComponent(this.font, this.text, {this.scale = 1, super.position, super.anchor}) {
    size = Vector2(font.measure(text, scale: scale), font.lineHeight * scale);
  }

  final BitmapFont font;
  final String text;
  final double scale;

  @override
  void render(ui.Canvas canvas) => font.draw(canvas, text, ui.Offset.zero, scale: scale);
}
"""


def flame_dart(anim: bool, nine: bool, parallax: bool, font: bool) -> str:
    out = FLAME_HEAD + (FLAME_UI_IMPORT if nine else "")
    for on, body in ((anim, FLAME_ANIM), (nine, FLAME_NINE), (parallax, FLAME_PARALLAX), (font, FLAME_FONT)):
        if on:
            out += body
    return out


def nine_slices_dart(entries: list[tuple[str, str, tuple[int, int, int, int], tuple[int, int]]]) -> str:
    """entries: (name, asset path, (l, t, r, b), (w, h)) → NineSliceSpec helpers + `AssetStudioNineSlices` constants."""
    names = dart_names([f"assets/ui/{n}.png" for n, *_ in entries])
    lines = ["", "class AssetStudioNineSlices {", "  AssetStudioNineSlices._();", ""]
    for nm, (_, path, (lft, top, rgt, bot), (w, h)) in zip(names, entries):
        lines.append(f"  static const NineSliceSpec {nm} = NineSliceSpec({_q(path)}, {lft}, {top}, {rgt}, {bot}, {w}, {h});")
    lines += ["}", ""]
    return UI_DART + "\n".join(lines)
